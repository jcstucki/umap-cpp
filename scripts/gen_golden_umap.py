#!/usr/bin/env python3
"""Generate golden values for the C++ UMAP class tests (tests/golden_umap.hpp).

Runs the *actual* reference UMAP (reference/umap + reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1, seeded random_state so upstream forces the
serial code paths) end to end, capturing per fit/transform:
  - the input data / held-out queries,
  - the initial embedding as passed to optimize_layout_euclidean (i.e. after
    init + noisy_scale_coords + the [0,10] rescale for fit; after
    init_graph_transform for transform),
  - the SGD rng_state, head/tail edge lists and epochs_per_sample,
  - the final embedding,
so the C++ port can be validated stage by stage.

Cases:
  a) 60x5 blobs,  init="random",   force_approximation_algorithm=True  (NN-descent path)
  b) 60x5 blobs,  init="spectral", force_approximation_algorithm=True  (NN-descent path)
  c) 200x5 blobs, init="spectral", small-data branch (exact kNN)
  d) 200x5 blobs, init="random",   small-data branch (fully deterministic
     path: expected bit-exact end to end in C++)
  plus transform() goldens for (a), (c) and (d) on held-out queries, and a
  fixed 150x4 iris-like dataset for the trustworthiness test.

Usage:
    NUMBA_NUM_THREADS=1 "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python scripts/gen_golden_umap.py > tests/golden_umap.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402
import scipy.sparse.csgraph  # noqa: E402

import umap.umap_ as um  # noqa: E402
from sklearn.manifold import trustworthiness  # noqa: E402


# ------------------------------------------------------------- capture patch
captured = []
_orig_opt = um.optimize_layout_euclidean


def _capturing_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                   n_vertices, epochs_per_sample, a, b, rng_state, *args,
                   **kwargs):
    captured.append({
        "init": head_embedding.copy(),
        "rng_state": rng_state.copy(),
        "n_epochs": n_epochs,
        "head": head.copy(),
        "tail": tail.copy(),
        "eps": epochs_per_sample.copy(),
    })
    return _orig_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                     n_vertices, epochs_per_sample, a, b, rng_state, *args,
                     **kwargs)


um.optimize_layout_euclidean = _capturing_opt


# ------------------------------------------------------------------ emitters
def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_umap.py -- do not edit by hand.")
out.append("// Golden values computed with the reference UMAP in reference/umap")
out.append("// (+ reference/pynndescent), NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_umap {")


def make_blobs(rng, n, dim, centers, std):
    pts = []
    per = n // len(centers)
    for ci, c in enumerate(centers):
        cnt = per if ci < len(centers) - 1 else n - per * (len(centers) - 1)
        pts.append(rng.randn(cnt, dim) * std + np.asarray(c))
    return np.vstack(pts).astype(np.float32)


def graph_components(model):
    # Number of connected components of the *filtered* graph the spectral
    # init actually sees (fit filters weights before initialisation).
    g = model.graph_.tocoo().copy()
    n_epochs = 500 if g.shape[0] <= 10000 else 200
    g.data[g.data < (g.data.max() / float(n_epochs))] = 0.0
    g.eliminate_zeros()
    return scipy.sparse.csgraph.connected_components(g)[0]


def emit_fit(prefix, X, model, queries=None):
    fit_capture_idx = len(captured)
    emb = model.fit_transform(X)
    cap = captured[fit_capture_idx]
    n, dim = X.shape
    out.append("// ---- %s: %dx%d, init=%s, force_approx=%s, seed=%s" % (
        prefix, n, dim, model.init, model.force_approximation_algorithm,
        model.random_state))
    out.append("static const std::int64_t %s_n = %d;" % (prefix, n))
    out.append("static const std::int64_t %s_dim = %d;" % (prefix, dim))
    out.append(carr("%s_X" % prefix, X))
    out.append(carr("%s_fit_init" % prefix, cap["init"]))
    out.append(carr("%s_fit_rng_state" % prefix, cap["rng_state"],
                    "std::int64_t"))
    out.append("static const int %s_fit_n_epochs = %d;" % (prefix,
                                                           cap["n_epochs"]))
    out.append("static const std::int64_t %s_fit_n_edges = %d;" % (
        prefix, len(cap["head"])))
    out.append(carr("%s_fit_head" % prefix, cap["head"], "std::int32_t"))
    out.append(carr("%s_fit_tail" % prefix, cap["tail"], "std::int32_t"))
    out.append(carr("%s_fit_eps" % prefix, cap["eps"], "double"))
    out.append(carr("%s_embedding" % prefix, emb))
    if queries is not None:
        t_capture_idx = len(captured)
        temb = model.transform(queries)
        tcap = captured[t_capture_idx]
        out.append("static const std::int64_t %s_nq = %d;" % (
            prefix, queries.shape[0]))
        out.append(carr("%s_queries" % prefix, queries))
        out.append(carr("%s_t_init" % prefix, tcap["init"]))
        out.append(carr("%s_t_rng_state" % prefix, tcap["rng_state"],
                        "std::int64_t"))
        out.append("static const int %s_t_n_epochs = %d;" % (
            prefix, tcap["n_epochs"]))
        out.append("static const std::int64_t %s_t_n_edges = %d;" % (
            prefix, len(tcap["head"])))
        out.append(carr("%s_t_head" % prefix, tcap["head"], "std::int32_t"))
        out.append(carr("%s_t_tail" % prefix, tcap["tail"], "std::int32_t"))
        out.append(carr("%s_t_eps" % prefix, tcap["eps"], "double"))
        out.append(carr("%s_t_embedding" % prefix, temb))
    out.append("")
    return emb


rng = np.random.RandomState(1234)
centers5 = [[0.0] * 5, [2.0, 1.5, 0.0, -1.0, 0.5], [-1.5, 2.0, 1.0, 0.5, -1.0]]

# ---- case a/b: 60x5, NN-descent path (force_approximation_algorithm=True)
Xab = make_blobs(rng, 60, 5, centers5, 1.0)
Qab = make_blobs(np.random.RandomState(77), 20, 5, centers5, 1.0)

model_a = um.UMAP(init="random", random_state=42,
                  force_approximation_algorithm=True)
emit_fit("ca", Xab, model_a, queries=Qab)

model_b = um.UMAP(init="spectral", random_state=42,
                  force_approximation_algorithm=True)
emit_fit("cb", Xab, model_b)
ncomp_b = graph_components(model_b)
out.append("// case cb filtered-graph components: %d" % ncomp_b)
assert ncomp_b == 1, "case b graph must be connected for spectral parity"
out.append("")

# ---- case c: 200x5, small-data branch, spectral init
Xc = make_blobs(np.random.RandomState(4321), 200, 5, centers5, 1.0)
Qc = make_blobs(np.random.RandomState(99), 40, 5, centers5, 1.0)
model_c = um.UMAP(init="spectral", random_state=42)
emit_fit("cc", Xc, model_c, queries=Qc)
ncomp_c = graph_components(model_c)
out.append("// case cc filtered-graph components: %d" % ncomp_c)
assert ncomp_c == 1, "case c graph must be connected for spectral parity"
out.append("")

# ---- case d: 200x5, small-data branch, random init (bit-exact candidate).
# a/b are passed explicitly (with the values scipy's curve_fit produces for
# the default spread/min_dist): the C++ find_ab_params LM implementation
# reaches the same minimum only to ~1e-7 relative, which would otherwise be
# the sole source of end-to-end divergence on this fully deterministic path.
ab_a, ab_b = um.find_ab_params(1.0, 0.1)
out.append("static const double cd_a = %.17g;" % ab_a)
out.append("static const double cd_b = %.17g;" % ab_b)
model_d = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b)
emit_fit("cd", Xc, model_d, queries=Qc)

# ---- case e: TIE-HEAVY transform (audit 2026-08-29, c09/c11). Integer-grid
# data with duplicate rows: query-to-training euclidean distances tie
# EXACTLY, including at the k = n_neighbors boundary, so the transform-side
# selection (numpy np.argpartition introselect + np.argsort) picks tied
# neighbours differently from numba's fit-side quickselect / any stable
# "ties by ascending index" stand-in. Same fully deterministic path as case
# d (small data, random init, explicit a/b) -> bit-exact end to end.
rng_e = np.random.RandomState(31337)
Xe = rng_e.randint(0, 4, size=(140, 4)).astype(np.float32)
Qe = rng_e.randint(0, 4, size=(35, 4)).astype(np.float32)
ke = 15  # default n_neighbors
dm_e = np.sqrt(((Qe[:, None, :].astype(np.float64) -
                 Xe[None, :, :].astype(np.float64)) ** 2).sum(-1))
srt_e = np.sort(dm_e, axis=1)
n_tied_e = int((srt_e[:, ke - 1] == srt_e[:, ke]).sum())
assert n_tied_e >= 8, "tie-heavy case must straddle the k boundary: %d" % \
    n_tied_e
part_e = np.argpartition(dm_e, ke, axis=1)[:, :ke]
stable_e = np.argsort(dm_e, axis=1, kind="stable")[:, :ke]
assert any(set(part_e[i]) != set(stable_e[i]) for i in range(dm_e.shape[0])), \
    "numpy introselect must pick a different tied subset than a stable sort"
out.append("// case ce: %d/%d query rows have an exact tie at the k=%d "
           "boundary" % (n_tied_e, Qe.shape[0], ke))
model_e = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b)
emit_fit("ce", Xe, model_e, queries=Qe)

# ---- iris-like 150x4 dataset for the trustworthiness test
centers4 = [[5.0, 3.4, 1.5, 0.2], [5.9, 2.8, 4.3, 1.3], [6.6, 3.0, 5.6, 2.0]]
Xt = make_blobs(np.random.RandomState(2024), 150, 4, centers4, 0.35)
model_t = um.UMAP(n_neighbors=10, min_dist=0.01, random_state=42)
emb_t = model_t.fit_transform(Xt)
tw_py = trustworthiness(Xt, emb_t, n_neighbors=5)
out.append("// ---- iris-like trustworthiness dataset (python UMAP scores %.5f)"
           % tw_py)
out.append("static const std::int64_t tw_n = %d;" % Xt.shape[0])
out.append("static const std::int64_t tw_dim = %d;" % Xt.shape[1])
out.append(carr("tw_X", Xt))
out.append("static const double tw_python = %.9g;" % tw_py)
out.append("")

out.append("}  // namespace golden_umap")
print("\n".join(out))
print("// components: cb=%d cc=%d" % (ncomp_b, ncomp_c), file=sys.stderr)
