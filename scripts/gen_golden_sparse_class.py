#!/usr/bin/env python3
"""Generate golden values for the sparse UMAP-class wiring tests
(tests/golden_sparse_class.hpp).

Runs the *actual* reference UMAP (reference/umap + reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1, seeded) on scipy.sparse CSR input.

Cases:
  p1) 200x50 density 0.1, euclidean, small-data branch, init="random",
      explicit a/b -- fit_transform AND transform goldens (bit-exact ambition)
  p2) p1 with metric="cosine"
  p5) p1 data with duplicated rows + unique=True (csr_unique path, bit-exact)
  p3) 300x50 sparse blobs, euclidean, force_approximation_algorithm=True
      (sparse NN-descent + SparsePreparedIndex) -- graph structure exact,
      embeddings at trustworthiness level (numba fastmath dists ~1 ulp)
  p4) p3 with metric="cosine" (angular trees; transform epsilon 0.24)

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python \
        scripts/gen_golden_sparse_class.py > tests/golden_sparse_class.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402

import umap.umap_ as um  # noqa: E402
from sklearn.manifold import trustworthiness  # noqa: E402


def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


def csr_arrays(name, X):
    assert X.has_sorted_indices
    return [
        "static const std::int64_t %s_n = %d;" % (name, X.shape[0]),
        "static const std::int64_t %s_dim = %d;" % (name, X.shape[1]),
        carr("%s_indptr" % name, X.indptr, "std::int32_t"),
        carr("%s_indices" % name, X.indices, "std::int32_t"),
        carr("%s_data" % name, X.data, "float"),
    ]


out = []
out.append("// Auto-generated by scripts/gen_golden_sparse_class.py -- do not edit.")
out.append("// Golden values computed with the reference UMAP in reference/umap")
out.append("// (+ reference/pynndescent), NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_sparse_class {")

ab_a, ab_b = um.find_ab_params(1.0, 0.1)
out.append("static const double sp_a = %.17g;" % ab_a)
out.append("static const double sp_b = %.17g;" % ab_b)
out.append("")


def emit_fit(prefix, X, model, queries=None, emit_graph_structure=False,
             emit_dense=False):
    emb = model.fit_transform(X)
    g = model.graph_.tocsr().copy()
    g.sort_indices()
    out.append("// ---- %s: metric=%s force_approx=%s unique=%s" % (
        prefix, model.metric, model.force_approximation_algorithm,
        model.unique))
    out.extend(csr_arrays(prefix, X))
    out.append(carr("%s_embedding" % prefix, emb))
    if emit_graph_structure:
        out.append(carr("%s_graph_indptr" % prefix, g.indptr, "std::int32_t"))
        out.append(carr("%s_graph_indices" % prefix, g.indices,
                        "std::int32_t"))
        out.append(carr("%s_graph_data" % prefix, g.data))
    if emit_dense:
        Xd = np.asarray(X.todense(), dtype=np.float32)
        out.append(carr("%s_dense" % prefix, Xd))
        tw = trustworthiness(Xd, emb, n_neighbors=5)
        out.append("static const double %s_fit_trust = %.9g;" % (prefix, tw))
    if queries is not None:
        temb = model.transform(queries)
        out.extend(csr_arrays("%s_q" % prefix, queries))
        out.append(carr("%s_t_embedding" % prefix, temb))
        if emit_dense:
            Qd = np.asarray(queries.todense(), dtype=np.float32)
            out.append(carr("%s_q_dense" % prefix, Qd))
            twq = trustworthiness(Qd, temb, n_neighbors=5)
            out.append("static const double %s_t_trust = %.9g;" % (prefix,
                                                                   twq))
    out.append("")
    return emb


# ---- p1/p2: 200x50 d=0.1 random sparse, small-data branch (bit-exact).
rs1 = np.random.RandomState(9001)
X1 = scipy.sparse.random(200, 50, density=0.1, format="csr", random_state=rs1,
                         dtype=np.float32)
X1.sort_indices()
# Guarantee non-empty rows (all-zero rows break cosine normalisation parity
# testing and are degenerate for kNN).
for row in range(X1.shape[0]):
    if X1.indptr[row] == X1.indptr[row + 1]:
        raise SystemExit("empty row in X1; pick another seed")
Q1 = scipy.sparse.random(30, 50, density=0.1, format="csr",
                         random_state=np.random.RandomState(77),
                         dtype=np.float32)
Q1.sort_indices()

m1 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b)
emit_fit("p1", X1, m1, queries=Q1)

# p2 uses a denser dataset: at density 0.1 over 50 dims many row pairs share
# no columns, so cosine distances tie at exactly 1.0 and numpy's *unstable*
# argpartition/argsort in transform() orders the tied neighbours differently
# from the C++ stable sort (a documented deviation -- upstream's fit-side
# fast_knn_indices is np.argsort(kind="stable") and matches everywhere).
rs2 = np.random.RandomState(9002)
X2 = scipy.sparse.random(200, 50, density=0.3, format="csr", random_state=rs2,
                         dtype=np.float32)
X2.sort_indices()
Q2 = scipy.sparse.random(30, 50, density=0.3, format="csr",
                         random_state=np.random.RandomState(9072),
                         dtype=np.float32)
Q2.sort_indices()
m2 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b, metric="cosine")
emit_fit("p2", X2, m2, queries=Q2)

# ---- p5: duplicated rows + unique=True (csr_unique object-row semantics).
X5 = scipy.sparse.vstack([X1[:60], X1[10:30], X1[:5]]).tocsr()
X5.sort_indices()
m5 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b, unique=True,
             n_neighbors=10)
emit_fit("p5", X5, m5)

# ---- p3/p4: sparse blobs, NN-descent branch (force_approximation).
def sparse_blobs(seed, n, dim, n_centers, keep):
    rng = np.random.RandomState(seed)
    centers = rng.randn(n_centers, dim) * 4.0
    rows = []
    for i in range(n):
        c = centers[i % n_centers]
        v = (c + rng.randn(dim)).astype(np.float32)
        mask = rng.rand(dim) < keep
        v = np.where(mask, v, 0.0).astype(np.float32)
        rows.append(v)
    Xd = np.vstack(rows)
    return scipy.sparse.csr_matrix(Xd)


X3 = sparse_blobs(555, 300, 50, 4, 0.25)
X3.sort_indices()
Q3 = sparse_blobs(556, 40, 50, 4, 0.25)
Q3.sort_indices()

m3 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
             force_approximation_algorithm=True)
emit_fit("p3", X3, m3, queries=Q3, emit_graph_structure=True,
         emit_dense=True)

m4 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b, metric="cosine",
             force_approximation_algorithm=True)
emit_fit("p4", X3, m4, queries=Q3, emit_graph_structure=True,
         emit_dense=True)

out.append("}  // namespace golden_sparse_class")
print("\n".join(out))
