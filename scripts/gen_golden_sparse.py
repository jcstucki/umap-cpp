#!/usr/bin/env python3
"""Generate golden values for the sparse-input port (tests/golden_sparse.hpp).

Runs the *actual* reference pynndescent (numba-jitted) checked out at
reference/pynndescent, plus sklearn for the small-data brute-force path:
  * sparse aux ops (arr_union/arr_intersect/sparse_sum/sparse_diff/sparse_mul)
  * sparse metrics incl. fast alternatives + corrections, on edge-case pairs
  * sparse RP-tree splits and whole-tree leaf arrays
  * end-to-end sparse NN-descent kNN graphs (NNDescent, seed 42,
    NUMBA_NUM_THREADS=1) -- the C++ port aims for index-identical results
  * sklearn pairwise_distances + stable-argsort brute-force kNN goldens

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python scripts/gen_golden_sparse.py \
        > tests/golden_sparse.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_CANDIDATE_REFS = [
    os.path.join(REPO, "reference"),
    "/Users/jake/Desktop/Code Projects/git repos/UMAP-C++/reference",
]
for _ref in _CANDIDATE_REFS:
    if os.path.isdir(os.path.join(_ref, "pynndescent")):
        sys.path.insert(0, os.path.join(_ref, "pynndescent"))
        break
else:
    raise SystemExit("reference/pynndescent not found")

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402
from sklearn.metrics import pairwise_distances  # noqa: E402

from pynndescent import sparse as pysparse  # noqa: E402
from pynndescent import rp_trees  # noqa: E402
from pynndescent.pynndescent_ import NNDescent  # noqa: E402

INT32_MIN = np.iinfo(np.int32).min + 1
INT32_MAX = np.iinfo(np.int32).max - 1


def fmt_float(v):
    v = float(v)
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "std::int8_t", "std::uint8_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


def csr_arrays(name, X):
    """Emit indptr/indices/data arrays + shape constants for a CSR matrix."""
    assert X.has_sorted_indices
    lines = [
        "static const std::int64_t %s_n = %d;" % (name, X.shape[0]),
        "static const std::int64_t %s_dim = %d;" % (name, X.shape[1]),
        carr("%s_indptr" % name, X.indptr, "std::int32_t"),
        carr("%s_indices" % name, X.indices, "std::int32_t"),
        carr("%s_data" % name, X.data, "float"),
    ]
    return lines


out = []
out.append("// Auto-generated by scripts/gen_golden_sparse.py -- do not edit by hand.")
out.append("// Golden values computed with the reference pynndescent in reference/")
out.append("// (NUMBA_NUM_THREADS=1) plus sklearn pairwise_distances.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_sparse {")

# ------------------------------------------------------------------- aux ops
# Two sparse vectors with overlapping support and value cancellation:
#   v1 has -2.5 at col 7, v2 has +2.5 at col 7 -> sparse_sum drops it;
#   equal values at col 4 -> sparse_diff drops it.
v1_ind = np.array([0, 4, 7, 9, 15], dtype=np.int32)
v1_dat = np.array([1.5, 2.25, -2.5, 0.375, 4.0], dtype=np.float32)
v2_ind = np.array([2, 4, 7, 15, 21], dtype=np.int32)
v2_dat = np.array([-1.25, 2.25, 2.5, 0.5, 3.5], dtype=np.float32)

out.append(carr("aux_v1_ind", v1_ind, "std::int32_t"))
out.append(carr("aux_v1_data", v1_dat, "float"))
out.append(carr("aux_v2_ind", v2_ind, "std::int32_t"))
out.append(carr("aux_v2_data", v2_dat, "float"))

u = pysparse.arr_union(v1_ind, v2_ind)
ix = pysparse.arr_intersect(v1_ind, v2_ind)
out.append(carr("aux_union", u, "std::int32_t"))
out.append(carr("aux_intersect", ix, "std::int32_t"))

s_ind, s_dat = pysparse.sparse_sum(v1_ind, v1_dat, v2_ind, v2_dat)
out.append(carr("aux_sum_ind", s_ind, "std::int32_t"))
out.append(carr("aux_sum_data", s_dat, "float"))
d_ind, d_dat = pysparse.sparse_diff(v1_ind, v1_dat, v2_ind, v2_dat)
out.append(carr("aux_diff_ind", d_ind, "std::int32_t"))
out.append(carr("aux_diff_data", d_dat, "float"))
m_ind, m_dat = pysparse.sparse_mul(v1_ind, v1_dat, v2_ind, v2_dat)
out.append(carr("aux_mul_ind", np.asarray(list(m_ind)), "std::int32_t"))
out.append(carr("aux_mul_data", np.asarray(list(m_dat)), "float"))

# ------------------------------------------------------------------- metrics
# A bank of vector pairs: generic overlap, empty vs empty, empty vs nonempty,
# disjoint supports, identical rows, plus random sparse pairs.
rs = np.random.RandomState(42)
pairs = [
    (v1_ind, v1_dat, v2_ind, v2_dat),
    (np.array([], dtype=np.int32), np.array([], dtype=np.float32),
     np.array([], dtype=np.int32), np.array([], dtype=np.float32)),
    (np.array([], dtype=np.int32), np.array([], dtype=np.float32),
     v2_ind, v2_dat),
    (np.array([1, 5, 9], dtype=np.int32),
     np.array([0.5, -1.5, 2.0], dtype=np.float32),
     np.array([0, 4, 12], dtype=np.int32),
     np.array([1.0, 3.0, -0.25], dtype=np.float32)),
    (v1_ind, v1_dat, v1_ind, v1_dat.copy()),
]
for _ in range(15):
    n1 = rs.randint(0, 12)
    n2 = rs.randint(0, 12)
    i1 = np.sort(rs.choice(30, size=n1, replace=False)).astype(np.int32)
    i2 = np.sort(rs.choice(30, size=n2, replace=False)).astype(np.int32)
    d1 = rs.uniform(-2, 2, size=n1).astype(np.float32)
    d2 = rs.uniform(-2, 2, size=n2).astype(np.float32)
    pairs.append((i1, d1, i2, d2))

pair_offsets = [0]
p_ind = []
p_dat = []
for i1, d1, i2, d2 in pairs:
    p_ind.append(i1)
    p_dat.append(d1)
    pair_offsets.append(pair_offsets[-1] + len(i1))
    p_ind.append(i2)
    p_dat.append(d2)
    pair_offsets.append(pair_offsets[-1] + len(i2))

out.append("static const std::int64_t metric_n_pairs = %d;" % len(pairs))
out.append(carr("metric_vec_offsets", pair_offsets, "std::int32_t"))
out.append(carr("metric_vec_ind", np.concatenate(p_ind), "std::int32_t"))
out.append(carr("metric_vec_data", np.concatenate(p_dat), "float"))

metric_fns = [
    ("euclidean", pysparse.sparse_euclidean),
    ("sqeuclidean", pysparse.sparse_squared_euclidean),
    ("manhattan", pysparse.sparse_manhattan),
    ("cosine", pysparse.sparse_cosine),
    ("alt_cosine", pysparse.sparse_alternative_cosine),
]
for mname, fn in metric_fns:
    vals = [np.float32(fn(i1, d1, i2, d2)) for (i1, d1, i2, d2) in pairs]
    out.append(carr("metric_%s" % mname, vals, "float"))

# corrections applied elementwise (f4 in / f4-cast out, as NNDescent does)
corr_sqrt_in = np.array(
    [0.0, 1e-8, 1e-7, 0.25, 1.0, 2.0, 4.0, 12.5, 3.4e38], dtype=np.float32
)
out.append(carr("corr_sqrt_in", corr_sqrt_in, "float"))
out.append(carr("corr_sqrt", np.sqrt(corr_sqrt_in).astype(np.float32), "float"))
corr_alt_in = np.array(
    [0.0, 1e-8, 5e-8, 1e-7, 1.0000001e-7, 2e-7, -0.5, 0.25, 1.0, 4.0, 12.5,
     3.4e38],
    dtype=np.float32,
)
out.append(carr("corr_alt_in", corr_alt_in, "float"))
out.append(carr(
    "corr_alt_cosine",
    pysparse.sparse_correct_alternative_cosine(corr_alt_in).astype(np.float32),
    "float",
))

# ------------------------------------------------------------ RP-tree splits
rsp = np.random.RandomState(5)
split_X = scipy.sparse.random(
    12, 8, density=0.4, format="csr", random_state=rsp, dtype=np.float32
)
# include negative values so euclidean margins are two-sided
split_X.data = (split_X.data * 2.0 - 0.5).astype(np.float32)
split_X.sort_indices()
split_indices = np.arange(12, dtype=np.int32)
out.extend(csr_arrays("split", split_X))

st = np.array([987654321, -123456789, 555555555], dtype=np.int64)
out.append(carr("split_rng_state", st, "std::int64_t"))

st_e = st.copy()
el, er, _, _ = rp_trees.sparse_euclidean_random_projection_split(
    split_X.indices, split_X.indptr, split_X.data, split_indices, st_e
)
out.append(carr("esplit_left", el, "std::int32_t"))
out.append(carr("esplit_right", er, "std::int32_t"))
out.append(carr("esplit_rng_after", st_e, "std::int64_t"))

st_a = st.copy()
al, ar, _, _ = rp_trees.sparse_angular_random_projection_split(
    split_X.indices, split_X.indptr, split_X.data, split_indices, st_a
)
out.append(carr("asplit_left", al, "std::int32_t"))
out.append(carr("asplit_right", ar, "std::int32_t"))
out.append(carr("asplit_rng_after", st_a, "std::int64_t"))

# ------------------------------------------------------------- RP-tree leaves
rst = np.random.RandomState(11)
tree_X = scipy.sparse.random(
    100, 10, density=0.35, format="csr", random_state=rst, dtype=np.float32
)
tree_X.sort_indices()
tree_rng = np.array([-2091788700, 121212121, 987001234], dtype=np.int64)
out.extend(csr_arrays("tree", tree_X))
out.append(carr("tree_rng_state", tree_rng, "std::int64_t"))

for angular, tag in ((False, "etree"), (True, "atree")):
    t = rp_trees.make_sparse_tree(
        tree_X.indices, tree_X.indptr, tree_X.data, tree_rng.copy(), 15,
        angular, 200
    )
    leaves = rp_trees.get_leaves_from_tree(t, np.int32(t.leaf_size))
    out.append("static const std::int64_t %s_n_leaves = %d;" % (tag, leaves.shape[0]))
    out.append("static const std::int64_t %s_leaf_width = %d;" % (tag, leaves.shape[1]))
    out.append(carr("%s_leaves" % tag, leaves, "std::int32_t"))

# --------------------------------------------- end-to-end sparse NN-descent
# UMAP's NNDescent invocation on sparse X (seed 42, NUMBA_NUM_THREADS=1):
#   n_trees = min(64, 5 + round(sqrt(n)/20)), n_iters = max(5, round(log2 n)),
#   max_candidates=60, low_memory=True, compressed=False.
def nnd_golden(tag, X, k, metric):
    n = X.shape[0]
    n_trees = min(64, 5 + int(round(n ** 0.5 / 20.0)))
    n_iters = max(5, int(round(np.log2(n))))
    index = NNDescent(
        X,
        n_neighbors=k,
        metric=metric,
        random_state=42,
        n_trees=n_trees,
        n_iters=n_iters,
        max_candidates=60,
        low_memory=True,
        compressed=False,
        verbose=False,
    )
    ind, dist = index.neighbor_graph
    lines = csr_arrays(tag, X)
    lines.append("static const std::int64_t %s_k = %d;" % (tag, k))
    lines.append(carr("%s_knn_ind" % tag, ind, "std::int32_t"))
    lines.append(carr("%s_knn_dist" % tag, dist.astype(np.float32), "float"))
    return lines

rsn = np.random.RandomState(1234)
nnd_e_X = scipy.sparse.random(
    300, 50, density=0.1, format="csr", random_state=rsn, dtype=np.float32
)
nnd_e_X.sort_indices()
out.extend(nnd_golden("nnd_e", nnd_e_X, 10, "euclidean"))

nnd_c_X = scipy.sparse.random(
    250, 40, density=0.12, format="csr", random_state=rsn, dtype=np.float32
)
nnd_c_X.sort_indices()
out.extend(nnd_golden("nnd_c", nnd_c_X, 10, "cosine"))

# ------------------------------------------ small-data brute-force kNN goldens
# UMAP.fit small-data branch: dmat = sklearn pairwise_distances(X, metric)
# (float64), then stable-argsort kNN (fast_knn_indices semantics).
rsb = np.random.RandomState(777)
bf_X = scipy.sparse.random(
    200, 50, density=0.1, format="csr", random_state=rsb, dtype=np.float32
)
# Guarantee no all-zero rows: sklearn's cosine treats zero vectors as
# similarity 0 (distance 1) while the sparse kernels return 0/1 by norm case,
# so an empty row would make the golden ambiguous rather than test the port.
_fill = scipy.sparse.csr_matrix(
    (np.full(200, 0.5, dtype=np.float32),
     (np.arange(200), np.arange(200) % 50)),
    shape=(200, 50),
)
bf_X = (bf_X + _fill).tocsr().astype(np.float32)
bf_X.sort_indices()
assert np.diff(bf_X.indptr).min() > 0
out.extend(csr_arrays("bf", bf_X))

for metric in ("euclidean", "cosine"):
    dmat = pairwise_distances(bf_X, metric=metric)
    knn_ind = np.argsort(dmat, kind="stable")[:, :10].astype(np.int32)
    knn_dist = dmat[np.arange(dmat.shape[0])[:, None], knn_ind]
    out.append(carr("bf_%s_knn_ind" % metric, knn_ind, "std::int32_t"))
    out.append(carr("bf_%s_knn_dist" % metric,
                    knn_dist.astype(np.float32), "float"))

out.append("}  // namespace golden_sparse")
print("\n".join(out))
