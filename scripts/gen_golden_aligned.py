# --------------------------------------- aligned_iris behavioral thresholds

# Upstream conftest fixture run (unseeded upstream; random_state=42 baked for
# the C++ port -- documented in tests/test_aligned.cpp). Verify the upstream
# thresholds hold for this seed in the reference implementation.
data5 = [IRIS[i:i + 50] for i in range(0, 125, 25)]
target5 = [iris.target[i:i + 50] for i in range(0, 125, 25)]
rel5 = [{a: a + 25 for a in range(25)} for _ in range(4)]
model5 = AlignedUMAP(random_state=42)
model5.fit(data5, relations=rel5)

from sklearn.metrics import pairwise_distances  # noqa: E402
from sklearn.cluster import KMeans  # noqa: E402
from sklearn.metrics import adjusted_rand_score  # noqa: E402


def nn_accuracy(true_nn, embd_nn):
    num_correct = 0.0
    for i in range(true_nn.shape[0]):
        num_correct += np.sum(np.isin(true_nn[i], embd_nn[i]))
    return num_correct / true_nn.size


accs = []
for i, sl in enumerate(data5):
    dmat = pairwise_distances(sl)
    true_nn = np.argsort(dmat, axis=1)[:, :10]
    edmat = pairwise_distances(model5.embeddings_[i])
    embd_nn = np.argsort(edmat, axis=1)[:, :10]
    accs.append(nn_accuracy(true_nn, embd_nn))
aris = []
for i in (1, 3):
    clusters = KMeans(n_clusters=2, n_init=10).fit_predict(model5.embeddings_[i])
    aris.append(adjusted_rand_score(target5[i], clusters))
print("// reference aligned_iris (random_state=42): nn_acc=%s ari=%s" %
      (["%.3f" % a for a in accs], ["%.3f" % a for a in aris]), file=sys.stderr)
assert all(a >= 0.65 for a in accs), accs
assert aris[0] >= 0.75 and aris[1] >= 0.40, aris

