def emit_slices(prefix, slices):
    out.append("static const int %s_n_slices = %d;" % (prefix, len(slices)))
    out.append(carr("%s_slice_rows" % prefix, [s.shape[0] for s in slices],
                    "std::int32_t"))
    for i, s in enumerate(slices):
        out.append(carr("%s_X%d" % (prefix, i), s.astype(np.float32)))


def emit_sgd_capture(prefix, cap):
    n = len(cap["init"])
    out.append("static const int %s_n_models = %d;" % (prefix, n))
    out.append("static const int %s_n_epochs = %d;" % (prefix, cap["n_epochs"]))
    out.append("static const double %s_lambda = %.17g;" % (prefix,
                                                           cap["lambda_"]))
    out.append("static const bool %s_move_other = %s;" %
               (prefix, "true" if cap["move_other"] else "false"))
    out.append(carr("%s_rng_state" % prefix, cap["rng"], "std::int64_t"))
    rel = cap["rel"]
    out.append(carr("%s_rel_shape" % prefix, rel.shape, "std::int32_t"))
    out.append(carr("%s_rel" % prefix, rel, "std::int32_t"))
    out.append(carr("%s_reg" % prefix, cap["reg"]))
    for m in range(n):
        out.append(carr("%s_head%d" % (prefix, m), cap["heads"][m],
                        "std::int32_t"))
        out.append(carr("%s_tail%d" % (prefix, m), cap["tails"][m],
                        "std::int32_t"))
        out.append(carr("%s_eps%d" % (prefix, m), cap["eps"][m], "double"))
        out.append(carr("%s_init%d" % (prefix, m), cap["init"][m]))
        out.append(carr("%s_final%d" % (prefix, m), cap["final"][m]))
        out.append("static const int %s_rows%d = %d;" %
                   (prefix, m, cap["init"][m].shape[0]))


def emit_graph(prefix, g):
    out.append(carr("%s_indptr" % prefix, g.indptr, "std::int32_t"))
    out.append(carr("%s_indices" % prefix, g.indices, "std::int32_t"))
    out.append(carr("%s_data" % prefix, g.data))


