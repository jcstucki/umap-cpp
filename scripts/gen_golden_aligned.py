# ------------------------------------------------- numba np.random goldens


@numba.njit()
def _seed_shuffle(s, n):
    arr = np.arange(n).astype(np.int32)
    np.random.seed(s)
    np.random.shuffle(arr)
    return arr


@numba.njit()
def _seed_shuffle_uniform(s, n, k):
    arr = np.arange(n).astype(np.int32)
    np.random.seed(s)
    np.random.shuffle(arr)
    u = np.random.uniform(-10.0, 10.0, k)
    return arr, u


NPRAND_CASES = [(0, 5), (1, 2), (42, 3), (42, 8), (189212, 5), (4294967295, 7)]
out.append("// numba np.random.seed + np.random.shuffle(arange(n).astype(i4))")
out.append(carr("nprand_seeds", [s for s, _ in NPRAND_CASES], "std::int64_t"))
out.append(carr("nprand_ns", [n for _, n in NPRAND_CASES], "std::int32_t"))
perms = []
for s, n in NPRAND_CASES:
    perms.extend(list(_seed_shuffle(s, n)))
out.append(carr("nprand_perms", perms, "std::int32_t"))
arr_u, u = _seed_shuffle_uniform(42, 5, 6)
out.append("// seed(42); shuffle(arange(5)); uniform(-10, 10, 6)")
out.append(carr("nprand_u_perm", arr_u, "std::int32_t"))
out.append(carr("nprand_u_vals", u, "double"))
out.append("")

# ---------------------------------------------------------- capture patches

captured_sgd = []
_orig_opt = au.optimize_layout_aligned_euclidean


def _capturing_opt(head_embeddings, tail_embeddings, heads, tails, n_epochs,
                   epochs_per_sample, regularisation_weights, relations,
                   rng_state, **kwargs):
    entry = {
        "init": [np.asarray(e).copy() for e in head_embeddings],
        "heads": [np.asarray(h).copy() for h in heads],
        "tails": [np.asarray(t).copy() for t in tails],
        "eps": [np.asarray(e).copy() for e in epochs_per_sample],
        "reg": np.asarray(regularisation_weights).copy(),
        "rel": np.asarray(relations).copy(),
        "rng": np.asarray(rng_state).copy(),
        "n_epochs": n_epochs,
        "lambda_": kwargs.get("lambda_", 5e-3),
        "move_other": kwargs.get("move_other", False),
    }
    result = _orig_opt(head_embeddings, tail_embeddings, heads, tails,
                       n_epochs, epochs_per_sample, regularisation_weights,
                       relations, rng_state, **kwargs)
    entry["final"] = [np.asarray(e).copy() for e in result]
    captured_sgd.append(entry)
    return result


au.optimize_layout_aligned_euclidean = _capturing_opt

captured_spectral = []
_orig_spectral = au.spectral_layout


def _capturing_spectral(data, graph, dim, random_state, **kwargs):
    r = _orig_spectral(data, graph, dim, random_state, **kwargs)
    captured_spectral.append(np.asarray(r).copy())
    return r


au.spectral_layout = _capturing_spectral

captured_procrustes = []
_orig_procrustes = au.procrustes_align


def _capturing_procrustes(embedding_base, embedding_to_align, anchors):
    r = _orig_procrustes(embedding_base, embedding_to_align, anchors)
    captured_procrustes.append({
        "base": np.asarray(embedding_base).copy(),
        "to_align": np.asarray(embedding_to_align).copy(),
        "anchors": np.asarray(anchors).copy(),
        "result": np.asarray(r).copy(),
    })
    return r


au.procrustes_align = _capturing_procrustes

captured_ife = []
_orig_ife = au.init_from_existing


def _capturing_ife(previous_embedding, graph, relations):
    g = graph.tocsr()
    r = _orig_ife(previous_embedding, graph, relations)
    # Assert the uniform(-10, 10) fallback never fired: every unrelated row
    # must have at least one related neighbour with nonzero weight.
    for i in range(g.shape[0]):
        if i in relations:
            continue
        w = 0.0
        for idx in range(g.indptr[i], g.indptr[i + 1]):
            if int(g.indices[idx]) in relations:
                w += g.data[idx]
        assert w != 0.0, "init_from_existing fallback fired for row %d" % i
    captured_ife.append({
        "prev": np.asarray(previous_embedding).copy(),
        "indptr": g.indptr.copy(),
        "indices": g.indices.copy(),
        "data": g.data.copy(),
        "rel_keys": np.asarray(sorted(relations.keys()), dtype=np.int64),
        "rel_vals": np.asarray([relations[k] for k in sorted(relations.keys())],
                               dtype=np.int64),
        "result": np.asarray(r).copy(),
    })
    return r


au.init_from_existing = _capturing_ife

