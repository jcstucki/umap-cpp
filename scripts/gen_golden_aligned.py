"""Generate golden values for the AlignedUMAP tests (tests/golden_aligned.hpp).

Runs the *actual* reference AlignedUMAP (reference/umap, numba-jitted,
NUMBA_NUM_THREADS=1, seeded random_state), monkeypatching
optimize_layout_aligned_euclidean / procrustes_align / spectral_layout /
init_from_existing in the aligned_umap module namespace to capture the exact
arrays flowing between the pipeline stages.

Captured per case:
  nprand) numba np.random goldens: np.random.seed(s) + np.random.shuffle
          permutations for several (seed, n), plus a shuffle+uniform sequence
          (regression anchors for aligned::NumbaNpRandom).
  as1)    3 aligned iris slices (40 rows, overlap 20), n_neighbors=8,
          random_state=42, defaults elsewhere. Mapper graph_ CSRs (with the
          explicit zeros the epoch filter writes through), expanded
          relations, regularisation weights, spectral inits (pre-procrustes,
          f32 expanded), procrustes inputs/outputs, seed triplet, and the
          FULL inputs + outputs of optimize_layout_aligned_euclidean
          (bit-exact SGD parity), plus final embeddings_ post NaN-masking.
  as2)    2 slices, window_size=1, alignment_regularisation=0.05,
          n_epochs=50 (a second, differently-shaped SGD parity case).
  au1)    fit on the first two as1 slices then update() with the third:
          init_from_existing inputs/output (asserted fallback-free) and the
          update-pass SGD inputs/outputs (move_other=False, frozen old
          models).

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python \
        scripts/gen_golden_aligned.py > tests/golden_aligned.hpp
"""
