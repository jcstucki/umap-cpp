#!/usr/bin/env python3
"""Generate golden values for the spectral-init tests from the reference
Python UMAP (reference/umap) + scipy/sklearn.

Usage:
    "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python scripts/gen_golden_spectral.py > tests/golden_spectral.hpp
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.environ.get("UMAP_REFERENCE", os.path.join(REPO, "reference", "umap"))
sys.path.insert(0, REF)

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402
import scipy.sparse.csgraph  # noqa: E402

from umap.spectral import spectral_layout, component_layout  # noqa: E402


def fmt_float(v):
    s = "%.9g" % v
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="double", fmt="{:.17g}"):
    flat = np.asarray(values).ravel()
    if fmt == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype.startswith("int"):
        vals = ", ".join(str(int(v)) for v in flat)
    else:
        vals = ", ".join(fmt.format(v) for v in flat)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


def normalized_laplacian(graph):
    """Exactly the construction in umap.spectral._spectral_layout."""
    g = graph.astype(np.float64)
    sqrt_deg = np.sqrt(np.asarray(g.sum(axis=0)).squeeze())
    I = scipy.sparse.identity(g.shape[0], dtype=np.float64)
    D = scipy.sparse.spdiags(1.0 / sqrt_deg, 0, g.shape[0], g.shape[0])
    return (I - D * g * D).toarray()


def sym_coo(n, rows, cols, vals):
    """Symmetric float32 CSR from upper-triangle COO triplets."""
    r = np.array(rows + cols, dtype=np.int32)
    c = np.array(cols + rows, dtype=np.int32)
    v = np.array(vals + vals, dtype=np.float32)
    return scipy.sparse.coo_matrix((v, (r, c)), shape=(n, n)).tocsr()


def upper_triplets(rng, nodes, lo=0.1, hi=1.0, extra=()):
    """Weighted clique over `nodes` (list) with distinct random weights."""
    rows, cols, vals = [], [], []
    for ai in range(len(nodes)):
        for bi in range(ai + 1, len(nodes)):
            rows.append(nodes[ai])
            cols.append(nodes[bi])
            vals.append(float(np.float32(rng.uniform(lo, hi))))
    return rows, cols, vals


out = []
out.append("// Auto-generated by scripts/gen_golden_spectral.py -- do not edit by hand.")
out.append("// Golden values computed with the reference Python UMAP + scipy/sklearn.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("")
out.append("namespace golden_spectral {")

# =====================================================================
# Graph A: connected, n = 16, non-degenerate spectrum (ring + chords).
# Golden eigenpairs of the normalized Laplacian via dense eigh.
# =====================================================================
rng = np.random.RandomState(1234)
n_a = 16
rows_a, cols_a, vals_a = [], [], []
for i in range(n_a):
    rows_a.append(i)
    cols_a.append((i + 1) % n_a)
    vals_a.append(float(np.float32(rng.uniform(0.3, 1.0))))
for i in range(0, n_a, 2):
    rows_a.append(i)
    cols_a.append((i + 5) % n_a)
    vals_a.append(float(np.float32(rng.uniform(0.1, 0.6))))
# canonicalize (row < col)
rc = [(min(r, c), max(r, c)) for r, c in zip(rows_a, cols_a)]
rows_a = [p[0] for p in rc]
cols_a = [p[1] for p in rc]
graph_a = sym_coo(n_a, rows_a, cols_a, vals_a)
assert scipy.sparse.csgraph.connected_components(graph_a)[0] == 1

L_a = normalized_laplacian(graph_a)
evals_a, evecs_a = np.linalg.eigh(L_a)
assert evals_a[1] - evals_a[0] > 1e-3 and evals_a[2] - evals_a[1] > 1e-3
assert evals_a[3] - evals_a[2] > 1e-3, "need non-degenerate spectrum"

# cross-check: upstream spectral_layout matches eigh columns up to sign
sl_a = spectral_layout(None, graph_a, 2, np.random.RandomState(42))
for j in range(2):
    ref = evecs_a[:, j + 1]
    err = min(np.abs(sl_a[:, j] - ref).max(), np.abs(sl_a[:, j] + ref).max())
    assert err < 1e-4, ("graph A upstream/eigh mismatch", j, err)

out.append("")
out.append("// Graph A: connected n=16 ring+chords; dense-eigh golden eigenpairs")
out.append("// of L = I - D^{-1/2} A D^{-1/2} (k = 3 smallest, dim = 2).")
out.append("static const int a_n = %d;" % n_a)
out.append(carr("a_rows", rows_a, "int32_t"))
out.append(carr("a_cols", cols_a, "int32_t"))
out.append(carr("a_vals", vals_a, "float", fmt="float"))
out.append(carr("a_evals", evals_a[:4]))
out.append(carr("a_evecs", evecs_a[:, 1:3]))  # n x 2, eigenvalue order 1,2

# =====================================================================
# Graph C: tiny connected n = 4 = dim + 2 (smallest size upstream accepts).
# =====================================================================
rng = np.random.RandomState(7)
n_c = 4
rows_c, cols_c, vals_c = upper_triplets(rng, list(range(n_c)), 0.2, 1.0)
graph_c = sym_coo(n_c, rows_c, cols_c, vals_c)
L_c = normalized_laplacian(graph_c)
evals_c, evecs_c = np.linalg.eigh(L_c)
assert evals_c[1] - evals_c[0] > 1e-3 and evals_c[2] - evals_c[1] > 1e-3
sl_c = spectral_layout(None, graph_c, 2, np.random.RandomState(42))
for j in range(2):
    ref = evecs_c[:, j + 1]
    err = min(np.abs(sl_c[:, j] - ref).max(), np.abs(sl_c[:, j] + ref).max())
    assert err < 1e-4, ("graph C upstream/eigh mismatch", j, err)

out.append("")
out.append("// Graph C: connected n=4 weighted clique (n = dim + 2 edge case).")
out.append("static const int c_n = %d;" % n_c)
out.append(carr("c_rows", rows_c, "int32_t"))
out.append(carr("c_cols", cols_c, "int32_t"))
out.append(carr("c_vals", vals_c, "float", fmt="float"))
out.append(carr("c_evals", evals_c[:3]))
out.append(carr("c_evecs", evecs_c[:, 1:3]))

# =====================================================================
# Graph B: two components (weighted cliques of sizes 8 and 7).
# Golden: full upstream spectral_layout -> multi_component_layout result.
# n_components = 2 <= 2 * dim so the meta embedding is the deterministic
# [[1, 0], [-1, 0]] and both components take the per-component spectral
# branch (sizes >= 2 * dim). data_range = 1 for both components.
# =====================================================================
rng = np.random.RandomState(99)
sizes_b = [8, 7]
n_b = sum(sizes_b)
rows_b, cols_b, vals_b = [], [], []
start = 0
for sz in sizes_b:
    r, c, v = upper_triplets(rng, list(range(start, start + sz)), 0.1, 1.0)
    rows_b += r
    cols_b += c
    vals_b += v
    start += sz
graph_b = sym_coo(n_b, rows_b, cols_b, vals_b)
nc_b, labels_b = scipy.sparse.csgraph.connected_components(graph_b)
assert nc_b == 2
assert labels_b.tolist() == [0] * 8 + [1] * 7
for sz, s in zip(sizes_b, [0, 8]):
    sub = graph_b[s : s + sz, s : s + sz]
    ev = np.linalg.eigvalsh(normalized_laplacian(sub))
    assert ev[1] - ev[0] > 1e-3 and ev[2] - ev[1] > 1e-3 and ev[3] - ev[2] > 1e-3, (
        "component spectrum must be non-degenerate for golden comparison",
        ev[:4],
    )

res_b = spectral_layout(None, graph_b, 2, np.random.RandomState(42))
assert res_b.dtype == np.float32 and res_b.shape == (n_b, 2)
meta_b = np.array([[1.0, 0.0], [-1.0, 0.0]])
# sanity: every point within the data_range box around its component center
for i in range(n_b):
    assert np.all(np.abs(res_b[i] - meta_b[labels_b[i]]) <= 1.0 + 1e-4)

out.append("")
out.append("// Graph B: two weighted cliques (sizes 8, 7); upstream")
out.append("// spectral_layout (multi_component_layout) result, float32.")
out.append("static const int b_n = %d;" % n_b)
out.append("static const int b_sizes[] = {8, 7};")
out.append(carr("b_rows", rows_b, "int32_t"))
out.append(carr("b_cols", cols_b, "int32_t"))
out.append(carr("b_vals", vals_b, "float", fmt="float"))
out.append(carr("b_result", res_b, "float", fmt="float"))

# =====================================================================
# Graph D: five components of size 6 (n_components = 5 > 2 * dim = 4)
# with source data -> component_layout (sklearn SpectralEmbedding of the
# centroid affinity) provides the meta embedding.
# =====================================================================
rng = np.random.RandomState(2718)
# O(1) centroid separation keeps the exp(-d^2) affinities well-conditioned
# (widely separated centers underflow the affinity matrix to ~0).
centers = np.array(
    [
        [0.0, 0.0, 0.0],
        [1.4, 0.0, 0.0],
        [0.0, 1.7, 0.2],
        [0.3, 0.0, 1.9],
        [1.2, 1.5, 1.3],
    ]
)
sizes_d = [6, 6, 6, 6, 6]
n_d = sum(sizes_d)
data_d = np.vstack(
    [
        centers[c] + rng.uniform(-0.1, 0.1, size=(sizes_d[c], 3))
        for c in range(len(sizes_d))
    ]
).astype(np.float32)
rows_d, cols_d, vals_d = [], [], []
start = 0
for sz in sizes_d:
    r, c, v = upper_triplets(rng, list(range(start, start + sz)), 0.1, 1.0)
    rows_d += r
    cols_d += c
    vals_d += v
    start += sz
graph_d = sym_coo(n_d, rows_d, cols_d, vals_d)
nc_d, labels_d = scipy.sparse.csgraph.connected_components(graph_d)
assert nc_d == 5
assert labels_d.tolist() == sum([[c] * 6 for c in range(5)], [])
for c, s in enumerate(range(0, n_d, 6)):
    sub = graph_d[s : s + 6, s : s + 6]
    ev = np.linalg.eigvalsh(normalized_laplacian(sub))
    assert ev[1] - ev[0] > 1e-3 and ev[2] - ev[1] > 1e-3 and ev[3] - ev[2] > 1e-3

meta_d = component_layout(
    data_d.astype(np.float64), nc_d, labels_d, 2, np.random.RandomState(42)
)
# centroid-affinity spectrum must be non-degenerate for exact meta parity
cents = np.vstack([data_d[labels_d == c].mean(axis=0) for c in range(5)])
dm = np.sqrt(((cents[:, None, :] - cents[None, :, :]) ** 2).sum(-1))
aff = np.exp(-(dm**2))
np.fill_diagonal(aff, 0.0)
dd = np.sqrt(aff.sum(axis=1))
Lm = np.eye(5) - aff / np.outer(dd, dd)
evm = np.linalg.eigvalsh(Lm)
assert np.all(np.diff(evm[:4]) > 1e-6), ("meta spectrum near-degenerate", evm)

res_d = spectral_layout(data_d, graph_d, 2, np.random.RandomState(42))
assert res_d.dtype == np.float32 and res_d.shape == (n_d, 2)

out.append("")
out.append("// Graph D: five weighted cliques of size 6 with 3-d source data;")
out.append("// component_layout meta embedding + upstream full result.")
out.append("static const int d_n = %d;" % n_d)
out.append("static const int d_n_features = 3;")
out.append("static const int d_n_components = 5;")
out.append(carr("d_data", data_d, "float", fmt="float"))
out.append(carr("d_labels", labels_d, "int32_t"))
out.append(carr("d_rows", rows_d, "int32_t"))
out.append(carr("d_cols", cols_d, "int32_t"))
out.append(carr("d_vals", vals_d, "float", fmt="float"))
out.append(carr("d_meta", meta_d))  # 5 x 2 float64
out.append(carr("d_result", res_d, "float", fmt="float"))

out.append("")
out.append("}  // namespace golden_spectral")
print("\n".join(out))
