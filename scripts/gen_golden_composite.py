#!/usr/bin/env python3
"""Generate golden values for the composite-model tests
(tests/golden_composite.hpp) from the reference Python UMAP.

Runs the actual reference UMAP (reference/umap + reference/pynndescent,
NUMBA_NUM_THREADS=1, seeded random_state) and composes fitted models with the
__mul__ / __add__ / __sub__ operators, capturing per composition:
  - the combined graph_ CSR *after* the embedding step (upstream's epoch
    weight filter writes explicit zeros back through the shared tocoo() data
    array, so the golden includes them) -- expected BIT-EXACT in C++ (the
    small-data fit graphs and the set-operation machinery are bit-exact),
  - the stage inputs of the composite simplicial_set_embedding call
    (post-rescale init, rng_state, n_epochs, filtered head/tail edge lists,
    epochs_per_sample) via a monkeypatch on optimize_layout_euclidean,
  - the trustworthiness of the Python composite embedding (reference level
    for the C++ quality guard; the embeddings themselves differ at the
    eigensolver level for spectral init, like the other spectral-init cases).

Fixtures reproduced: conftest.py nn_data (np.random.seed(189212), definition
order) and sklearn load_iris, matching tests/upstream_data.hpp.

Cases:
  * nn pair -- test_composite_trustworthiness's model1/model2 on nn_data[:50]
    (model2 is init from model1.embedding_; the *graphs* are init-independent,
    so they are bit-exact even though the embeddings drift at eigensolver
    level): model1 * model2 and model1 + model2.
  * iris pair -- test_composite_trustworthiness_on_iris's models on
    iris.data[:, :2] / iris.data[:, 2:]: union (+ full stage capture),
    intersection and contrast (im1 - im2).

Usage:
    NUMBA_NUM_THREADS=1 "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python \
        scripts/gen_golden_composite.py > tests/golden_composite.hpp
"""
import os
import sys
import warnings

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402
import scipy.sparse.csgraph  # noqa: E402

import umap.umap_ as um  # noqa: E402
from umap import UMAP  # noqa: E402
from sklearn.datasets import load_iris  # noqa: E402
from sklearn.manifold import trustworthiness  # noqa: E402


# ------------------------------------------------------------- capture patch
captured = []
_orig_opt = um.optimize_layout_euclidean


def _capturing_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                   n_vertices, epochs_per_sample, a, b, rng_state, *args,
                   **kwargs):
    captured.append({
        "init": head_embedding.copy(),
        "rng_state": rng_state.copy(),
        "n_epochs": n_epochs,
        "head": head.copy(),
        "tail": tail.copy(),
        "eps": epochs_per_sample.copy(),
    })
    return _orig_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                     n_vertices, epochs_per_sample, a, b, rng_state, *args,
                     **kwargs)


um.optimize_layout_euclidean = _capturing_opt


# ------------------------------------------------------------------ emitters
def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_composite.py -- do not"
           " edit by hand.")
out.append("// Golden values computed with the reference UMAP in"
           " reference/umap")
out.append("// (+ reference/pynndescent), NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_composite {")


def emit_graph(prefix, model):
    """result.graph_ as stored on the composite model: CSR including the
    explicit zeros the epoch filter wrote through the shared tocoo() data."""
    g = model.graph_
    assert scipy.sparse.issparse(g) and g.format == "csr", g.format
    assert g.has_sorted_indices
    assert g.dtype == np.float32
    out.append("static const std::int64_t %s_n = %d;" % (prefix, g.shape[0]))
    out.append("static const std::int64_t %s_nnz = %d;" % (prefix, g.nnz))
    out.append(carr("%s_indptr" % prefix, g.indptr, "std::int32_t"))
    out.append(carr("%s_indices" % prefix, g.indices, "std::int32_t"))
    out.append(carr("%s_data" % prefix, g.data, "float"))


def emit_capture(prefix, cap, spectral_init):
    out.append("static const int %s_n_epochs = %d;" % (prefix, cap["n_epochs"]))
    out.append("static const int %s_init_is_spectral = %d;"
               % (prefix, 1 if spectral_init else 0))
    out.append(carr("%s_rng_state" % prefix, cap["rng_state"], "std::int64_t"))
    out.append("static const std::int64_t %s_n_edges = %d;"
               % (prefix, cap["head"].shape[0]))
    out.append(carr("%s_head" % prefix, cap["head"], "std::int32_t"))
    out.append(carr("%s_tail" % prefix, cap["tail"], "std::int32_t"))
    out.append(carr("%s_eps" % prefix, cap["eps"], "double"))
    out.append(carr("%s_init" % prefix, cap["init"], "float"))


def spectral_init_used(model_before_embedding_graph):
    """The operators pick init='spectral' unless the *unfiltered* combined
    graph is disconnected."""
    n_comp = scipy.sparse.csgraph.connected_components(
        model_before_embedding_graph)[0]
    return n_comp == 1


# ------------------------------------------------- conftest data replication
np.random.seed(189212)
_spatial = np.vstack([np.random.randn(10, 20), np.zeros((2, 20))])
_binary = np.vstack([
    np.random.choice(a=[False, True], size=(10, 20), p=[0.66, 1 - 0.66]),
    np.zeros((2, 20), dtype="bool"),
])
nn_data = np.vstack([np.random.uniform(0, 1, size=(1000, 5)),
                     np.zeros((2, 5))])
iris = load_iris()


# ------------------------------------------------------------------- nn pair
data = nn_data[:50]
with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    model1 = UMAP(n_neighbors=10, min_dist=0.01, random_state=42,
                  n_epochs=50).fit(data)
    model2 = UMAP(n_neighbors=30, min_dist=0.01, random_state=42, n_epochs=50,
                  init=model1.embedding_).fit(data)

    captured.clear()
    model3 = model1 * model2
    cap_mul = captured[-1]
    captured.clear()
    model4 = model1 + model2
    cap_add = captured[-1]

out.append("")
out.append("// --- nn pair (test_composite_trustworthiness): nn_data[:50],")
out.append("// model1 = UMAP(n_neighbors=10, min_dist=0.01, random_state=42,"
           " n_epochs=50),")
out.append("// model2 = same but n_neighbors=30, init=model1.embedding_. ---")
emit_graph("nn_mul", model3)
emit_capture("nn_mul", cap_mul,
             spectral_init_used(model3.graph_))  # post-filter structure equal
emit_graph("nn_add", model4)
emit_capture("nn_add", cap_add, spectral_init_used(model4.graph_))
t_mul = trustworthiness(data, model3.embedding_, n_neighbors=10)
t_add = trustworthiness(data, model4.embedding_, n_neighbors=10)
out.append("static const double nn_mul_trust = %.17g;" % t_mul)
out.append("static const double nn_add_trust = %.17g;" % t_add)
print("nn pair: mul trust %.4f add trust %.4f (upstream threshold 0.80)"
      % (t_mul, t_add), file=sys.stderr)
assert t_mul >= 0.80 and t_add >= 0.80

# The composite init choice runs on the pre-filter graph; assert the
# connectivity decision is the same pre- and post-filter so the flag above is
# unambiguous (the explicit zeros do not change scipy's structure anyway).
for m in (model3, model4):
    g = m.graph_.copy()
    g.eliminate_zeros()
    assert (scipy.sparse.csgraph.connected_components(m.graph_)[0]
            == 1), "nn composite graph disconnected; goldens assume spectral"


# ----------------------------------------------------------------- iris pair
with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    iris_model1 = UMAP(n_neighbors=10, min_dist=0.01, random_state=42,
                       n_epochs=100).fit(iris.data[:, :2])
    iris_model2 = UMAP(n_neighbors=10, min_dist=0.01, random_state=42,
                       n_epochs=100).fit(iris.data[:, 2:])

    captured.clear()
    iu = iris_model1 + iris_model2
    cap_iu = captured[-1]
    captured.clear()
    ix = iris_model1 * iris_model2
    cap_ix = captured[-1]
    captured.clear()
    ic = iris_model1 - iris_model2
    cap_ic = captured[-1]

out.append("")
out.append("// --- iris pair (test_composite_trustworthiness_on_iris /")
out.append("// test_contrastive_trustworthiness_on_iris): models on"
           " iris.data[:, :2]")
out.append("// and iris.data[:, 2:], n_neighbors=10, min_dist=0.01,"
           " random_state=42,")
out.append("// n_epochs=100. ---")
emit_graph("iris_add", iu)
emit_capture("iris_add", cap_iu, spectral_init_used(iu.graph_))
emit_graph("iris_mul", ix)
out.append(carr("iris_mul_rng_state", cap_ix["rng_state"], "std::int64_t"))
out.append("static const int iris_mul_init_is_spectral = %d;"
           % (1 if spectral_init_used(ix.graph_) else 0))
emit_graph("iris_sub", ic)
out.append(carr("iris_sub_rng_state", cap_ic["rng_state"], "std::int64_t"))
out.append("static const int iris_sub_init_is_spectral = %d;"
           % (1 if spectral_init_used(ic.graph_) else 0))

t_iu = trustworthiness(iris.data, iu.embedding_, n_neighbors=10)
t_ix = trustworthiness(iris.data, ix.embedding_, n_neighbors=10)
t_ic = trustworthiness(iris.data, ic.embedding_, n_neighbors=10)
out.append("static const double iris_add_trust = %.17g;" % t_iu)
out.append("static const double iris_mul_trust = %.17g;" % t_ix)
out.append("static const double iris_sub_trust = %.17g;" % t_ic)
print("iris pair: add %.4f mul %.4f (threshold 0.82), sub %.4f (0.75)"
      % (t_iu, t_ix, t_ic), file=sys.stderr)
assert t_iu >= 0.82 and t_ix >= 0.82 and t_ic >= 0.75

# --------------------------------------------- stream-parity self-validation
# The composite embedding draws from a fresh RandomState(42): spectral init
# consumes normal(size=(n, dim + 1)) [discarded eigsh warm start] +
# noisy_scale_coords' normal(0, 1e-4, (n, dim)), then randint(...) for the
# SGD rng_state. Verify the captured rng_state against the replicated stream
# (the same replication the C++ class performs).
INT32_MIN = np.iinfo(np.int32).min + 1
INT32_MAX = np.iinfo(np.int32).max
for name, cap, n, spectral in (
    ("nn_mul", cap_mul, 50, True),
    ("nn_add", cap_add, 50, True),
    ("iris_add", cap_iu, 150, spectral_init_used(iu.graph_)),
):
    rs = np.random.RandomState(42)
    if spectral:
        rs.normal(size=(n, 3))
        rs.normal(0.0, 0.0001, size=(n, 2))
    else:
        rs.uniform(low=-10.0, high=10.0, size=(n, 2))
    expect = rs.randint(INT32_MIN, INT32_MAX, 3).astype(np.int64)
    assert np.array_equal(expect, cap["rng_state"]), (name, expect,
                                                      cap["rng_state"])
print("stream-parity self-validation passed", file=sys.stderr)

out.append("")
out.append("}  // namespace golden_composite")
print("\n".join(out))
