#!/usr/bin/env python3
"""Generate golden values for update() (tests/golden_update.hpp).

Runs the *actual* reference UMAP (reference/umap + reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1, seeded) fit + update flows.

Cases (all init="random", explicit a/b, i.e. deterministic paths the C++
port reproduces bit-exactly):
  u1) small -> small: euclidean 90x5 fit (n_epochs=100), update +25 rows.
      Captures: fit embedding, the SGD init update() builds (embedding_ +
      init_update means), post-update graph_ CSR (incl. the shared-buffer
      filter zeros), sigmas/rhos, final embedding.
  u2) standard branch: minkowski p=3 (its pow-chain NN-descent kernel is
      bit-reproducible, unlike fastmath euclidean) 4200x8 fit (n_epochs=200),
      update +30 rows via NNDescent.update + re-prepare. Captures: fit
      embedding, post-update kNN rows of the appended points, init rows of
      the appended points, final embedding.
  u3) small -> large transition: minkowski p=3 4090x8 fit (small branch),
      update +30 -> 4120 rows (>= 4096: builds a fresh NN-descent index from
      the transform_seed stream). Same captures as u2.
  u4) sparse small -> small: euclidean CSR 100x40 fit, update +20 rows.
      Captures: fit embedding, final embedding, post-update graph_ CSR.
  u5) chained small updates: a second update (+12 rows) of the u1 model --
      each update draws a *fresh* check_random_state(transform_seed) stream.
  u6) chained standard updates: a second update (+15 rows) of the u2 model --
      NNDescent.update continues the tau rng_state and the fit RandomState
      exactly where the first update left them.
  u7) chained update after the u3 small -> large transition: the index built
      *during* update 1 (from that update's transform_seed stream) is updated
      again, exercising the RandomState-instance handoff.

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python \
        scripts/gen_golden_update.py > tests/golden_update.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402

import umap.umap_ as um  # noqa: E402

# ------------------------------------------------------------- capture patch
captured = []
_orig_opt = um.optimize_layout_euclidean


def _capturing_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                   n_vertices, epochs_per_sample, a, b, rng_state, *args,
                   **kwargs):
    captured.append({
        "init": head_embedding.copy(),
        "n_epochs": n_epochs,
        "rng_state": rng_state.copy(),
    })
    return _orig_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                     n_vertices, epochs_per_sample, a, b, rng_state, *args,
                     **kwargs)


um.optimize_layout_euclidean = _capturing_opt


# ------------------------------------------------------------------ emitters
def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_update.py -- do not edit.")
out.append("// Golden values computed with the reference UMAP in")
out.append("// reference/umap (+ reference/pynndescent), NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_update {")

ab_a, ab_b = um.find_ab_params(1.0, 0.1)
out.append("static const double ab_a = %.17g;" % ab_a)
out.append("static const double ab_b = %.17g;" % ab_b)
out.append("")


def make_blobs(rng, n, dim, centers, std):
    pts = []
    per = n // len(centers)
    for ci, c in enumerate(centers):
        cnt = per if ci < len(centers) - 1 else n - per * (len(centers) - 1)
        pts.append(rng.randn(cnt, dim) * std + np.asarray(c))
    return np.vstack(pts).astype(np.float32)


def emit_graph(prefix, g):
    g = g.tocsr().copy()
    g.sort_indices()
    out.append(carr("%s_graph_indptr" % prefix, g.indptr, "std::int32_t"))
    out.append(carr("%s_graph_indices" % prefix, g.indices, "std::int32_t"))
    out.append(carr("%s_graph_data" % prefix, g.data))


rng = np.random.RandomState(2024)

# ---- u1: small -> small, euclidean --------------------------------------
X = make_blobs(rng, 115, 5, [[0] * 5, [5] * 5, [-5, 5, -5, 5, -5]], 1.0)
X1, X1new = X[:90], X[90:]
m = um.UMAP(n_neighbors=10, min_dist=0.01, n_epochs=100, init="random",
            random_state=42, a=ab_a, b=ab_b)
m.fit(X1)
fit_emb = m.embedding_.copy()
cap_idx = len(captured)
m.update(X1new)
m1 = m  # kept for the chained u5 update below
cap = captured[cap_idx]
out.append("// ---- u1: euclidean 90 + 25, small -> small")
out.append("static const int u1_n = 90;")
out.append("static const int u1_n_new = 25;")
out.append("static const int u1_dim = 5;")
out.append(carr("u1_X", X1))
out.append(carr("u1_X_new", X1new))
out.append(carr("u1_fit_embedding", fit_emb))
out.append(carr("u1_update_init", cap["init"]))
out.append("static const int u1_update_n_epochs = %d;" % cap["n_epochs"])
emit_graph("u1", m.graph_)
out.append(carr("u1_sigmas", m._sigmas))
out.append(carr("u1_rhos", m._rhos))
out.append(carr("u1_embedding", m.embedding_))
out.append("")

# ---- u2: standard branch, minkowski p=3 ---------------------------------
n2, d2 = 4200, 8
X = rng.uniform(size=(n2 + 30, d2)).astype(np.float32)
X2, X2new = X[:n2], X[n2:]
m = um.UMAP(n_neighbors=10, metric="minkowski", metric_kwds={"p": 3.0},
            n_epochs=200, init="random", random_state=42, a=ab_a, b=ab_b)
print("fitting u2 (standard, 4200x8 minkowski)...", file=sys.stderr)
m.fit(X2)
fit_emb = m.embedding_.copy()
cap_idx = len(captured)
print("updating u2...", file=sys.stderr)
m.update(X2new)
m2 = m  # kept for the chained u6 update below
cap = captured[cap_idx]
out.append("// ---- u2: minkowski p=3, 4200 + 30, standard branch")
out.append("static const int u2_n = %d;" % n2)
out.append("static const int u2_n_new = 30;")
out.append("static const int u2_dim = %d;" % d2)
out.append(carr("u2_X", X2))
out.append(carr("u2_X_new", X2new))
out.append(carr("u2_fit_embedding_tail", fit_emb[-40:]))
out.append(carr("u2_knn_indices_new", m._knn_indices[n2:], "std::int32_t"))
out.append(carr("u2_knn_dists_new", m._knn_dists[n2:]))
out.append(carr("u2_update_init_new", cap["init"][n2:]))
out.append("static const int u2_update_n_epochs = %d;" % cap["n_epochs"])
out.append(carr("u2_embedding", m.embedding_))
out.append("")

# ---- u3: small -> large transition, minkowski p=3 -----------------------
n3, d3 = 4090, 8
X = rng.uniform(size=(n3 + 30, d3)).astype(np.float32)
X3, X3new = X[:n3], X[n3:]
m = um.UMAP(n_neighbors=10, metric="minkowski", metric_kwds={"p": 3.0},
            n_epochs=200, init="random", random_state=42, a=ab_a, b=ab_b)
print("fitting u3 (small branch, 4090x8 minkowski pairwise)...",
      file=sys.stderr)
m.fit(X3)
fit_emb = m.embedding_.copy()
assert m._small_data
cap_idx = len(captured)
print("updating u3 (transition)...", file=sys.stderr)
m.update(X3new)
assert not m._small_data
m3 = m  # kept for the chained u7 update below
cap = captured[cap_idx]
out.append("// ---- u3: minkowski p=3, 4090 + 30, small -> large transition")
out.append("static const int u3_n = %d;" % n3)
out.append("static const int u3_n_new = 30;")
out.append("static const int u3_dim = %d;" % d3)
out.append(carr("u3_X", X3))
out.append(carr("u3_X_new", X3new))
out.append(carr("u3_fit_embedding_tail", fit_emb[-40:]))
out.append(carr("u3_knn_indices_new", m._knn_indices[n3:], "std::int32_t"))
out.append(carr("u3_knn_dists_new", m._knn_dists[n3:]))
out.append(carr("u3_update_init_new", cap["init"][n3:]))
out.append("static const int u3_update_n_epochs = %d;" % cap["n_epochs"])
out.append(carr("u3_embedding", m.embedding_))
out.append("")

# ---- u4: sparse small -> small, euclidean -------------------------------
rs = np.random.RandomState(777)
dense = rs.uniform(size=(120, 40)) * (rs.uniform(size=(120, 40)) < 0.15)
sp = scipy.sparse.csr_matrix(dense.astype(np.float32))
sp.sort_indices()
S1, S1new = sp[:100], sp[100:]
m = um.UMAP(n_neighbors=8, n_epochs=80, init="random", random_state=42,
            a=ab_a, b=ab_b)
m.fit(S1)
fit_emb = m.embedding_.copy()
m.update(S1new)
out.append("// ---- u4: sparse euclidean CSR 100 + 20, small -> small")
out.append("static const int u4_n = 100;")
out.append("static const int u4_n_new = 20;")
out.append("static const int u4_dim = 40;")
out.append(carr("u4_indptr", S1.indptr, "std::int32_t"))
out.append(carr("u4_indices", S1.indices, "std::int32_t"))
out.append(carr("u4_data", S1.data))
out.append(carr("u4_new_indptr", S1new.indptr, "std::int32_t"))
out.append(carr("u4_new_indices", S1new.indices, "std::int32_t"))
out.append(carr("u4_new_data", S1new.data))
out.append(carr("u4_fit_embedding", fit_emb))
emit_graph("u4", m.graph_)
out.append(carr("u4_embedding", m.embedding_))
out.append("")

# ---- u5: chained small update of the u1 model ---------------------------
# New rows must overlap the original blobs: numba's init_update raises
# ZeroDivisionError when an appended point has no original-data neighbours
# among its k nearest (a tight new blob triggers it -- covered by a raise
# test on the C++ side).
X5new = make_blobs(rng, 12, 5, [[0] * 5, [5] * 5], 1.0)
m1.update(X5new)
out.append("// ---- u5: second small update of the u1 model (+12 rows)")
out.append("static const int u5_n_new = 12;")
out.append(carr("u5_X_new", X5new))
emit_graph("u5", m1.graph_)
out.append(carr("u5_embedding", m1.embedding_))
out.append("")

# ---- u6: chained standard update of the u2 model ------------------------
X6new = rng.uniform(size=(15, d2)).astype(np.float32)
print("updating u6 (chained standard)...", file=sys.stderr)
m2.update(X6new)
out.append("// ---- u6: second standard update of the u2 model (+15 rows)")
out.append("static const int u6_n_new = 15;")
out.append(carr("u6_X_new", X6new))
out.append(carr("u6_knn_indices_new", m2._knn_indices[-15:], "std::int32_t"))
out.append(carr("u6_knn_dists_new", m2._knn_dists[-15:]))
out.append(carr("u6_embedding_tail", m2.embedding_[-60:]))
out.append("")

# ---- u7: chained update after the u3 transition -------------------------
X7new = rng.uniform(size=(15, d3)).astype(np.float32)
print("updating u7 (chained after transition)...", file=sys.stderr)
m3.update(X7new)
out.append("// ---- u7: second update of the u3 model (+15 rows; the index")
out.append("// was built during update 1 from that update's transform_seed")
out.append("// stream and is continued here)")
out.append("static const int u7_n_new = 15;")
out.append(carr("u7_X_new", X7new))
out.append(carr("u7_knn_indices_new", m3._knn_indices[-15:], "std::int32_t"))
out.append(carr("u7_knn_dists_new", m3._knn_dists[-15:]))
out.append(carr("u7_embedding_tail", m3.embedding_[-60:]))
out.append("")

out.append("}  // namespace golden_update")
print("\n".join(out))
print("captures: %d" % len(captured), file=sys.stderr)
