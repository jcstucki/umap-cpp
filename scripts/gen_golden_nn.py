#!/usr/bin/env python3
"""Generate golden values for the C++ NN-descent port (tests/golden_nn.hpp).

Runs the *actual* reference pynndescent checked out at reference/pynndescent
(numba-jitted). Deterministic pieces (heap pushes, deheap_sort, candidate
building, RP-tree splits/leaves, numpy RandomState seeding) are goldened
exactly; the full NN-descent kNN graph is validated by recall in the C++
tests instead (numba fastmath + parallel iteration order make bitwise
end-to-end parity infeasible).

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python scripts/gen_golden_nn.py > tests/golden_nn.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))

import numpy as np  # noqa: E402

from pynndescent.utils import (  # noqa: E402
    checked_flagged_heap_push,
    deheap_sort,
    make_heap,
    new_build_candidates,
    simple_heap_push,
)
from pynndescent import rp_trees  # noqa: E402

INT32_MIN = np.iinfo(np.int32).min + 1
INT32_MAX = np.iinfo(np.int32).max - 1


def fmt_float(v):
    v = float(v)
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "std::int8_t", "std::uint8_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_nn.py -- do not edit by hand.")
out.append("// Golden values computed with the reference pynndescent in reference/pynndescent.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_nn {")

# ------------------------------------------------- numpy RandomState seeding
# NNDescent seeding for random_state=42: rng_state, search_rng_state, then the
# per-tree states drawn inside make_forest (row-major, 3 per tree).
rs = np.random.RandomState(42)
rng_state_42 = rs.randint(INT32_MIN, INT32_MAX, 3).astype(np.int64)
search_rng_state_42 = rs.randint(INT32_MIN, INT32_MAX, 3).astype(np.int64)
tree_states_42_6 = rs.randint(INT32_MIN, INT32_MAX, size=(6, 3)).astype(np.int64)
out.append(carr("rng_state_seed42", rng_state_42, "std::int64_t"))
out.append(carr("search_rng_state_seed42", search_rng_state_42, "std::int64_t"))
out.append("// 6 trees x 3 state words (as drawn by make_forest after the two above)")
out.append(carr("tree_states_seed42_n6", tree_states_42_6, "std::int64_t"))

rs2 = np.random.RandomState(12345)
draws_12345 = rs2.randint(INT32_MIN, INT32_MAX, 12).astype(np.int64)
out.append(carr("randint_draws_seed12345", draws_12345, "std::int64_t"))

# --------------------------------------------------- umap parameter formulas
# n_trees = min(64, 5 + int(round(sqrt(N) / 20))); n_iters = max(5, round(log2 N))
param_ns = [50, 80, 100, 600, 900, 4096, 10000, 30000, 250000, 3000000]
n_trees_g = [min(64, 5 + int(round(n ** 0.5 / 20.0))) for n in param_ns]
n_iters_g = [max(5, int(round(np.log2(n)))) for n in param_ns]
out.append(carr("param_n", param_ns, "std::int64_t"))
out.append(carr("param_n_trees", n_trees_g, "std::int32_t"))
out.append(carr("param_n_iters", n_iters_g, "std::int32_t"))

# ------------------------------------------------------------ heap semantics
# A scripted sequence of checked_flagged_heap_push ops on one heap row.
heap = make_heap(1, 6)
push_ops = [
    (5.0, 7, 1), (3.0, 2, 1), (9.0, 4, 0), (1.0, 9, 1), (4.0, 4, 0),
    (2.5, 11, 0), (2.5, 11, 1), (0.5, 3, 1), (8.0, 5, 1), (3.5, 6, 0),
    (0.25, 12, 0), (3.0, 2, 0), (1.75, 1, 1),
]
push_rets = []
for d, idx, f in push_ops:
    r = checked_flagged_heap_push(
        heap[1][0], heap[0][0], heap[2][0], np.float32(d), np.int32(idx), np.uint8(f)
    )
    push_rets.append(int(r))
out.append("// checked_flagged_heap_push: ops (d, idx, flag) applied to a fresh heap row of size 6")
out.append(carr("push_ops_d", [o[0] for o in push_ops], "float"))
out.append(carr("push_ops_idx", [o[1] for o in push_ops], "std::int32_t"))
out.append(carr("push_ops_flag", [o[2] for o in push_ops], "std::int32_t"))
out.append(carr("push_rets", push_rets, "std::int32_t"))
out.append(carr("push_final_ind", heap[0][0], "std::int32_t"))
out.append(carr("push_final_dist", heap[1][0], "float"))
out.append(carr("push_final_flag", heap[2][0], "std::int32_t"))

# simple_heap_push (no dedup): same ops, priorities/indices only.
pri = np.full(6, np.inf, dtype=np.float32)
ind = np.full(6, -1, dtype=np.int32)
simple_rets = []
for d, idx, _ in push_ops:
    simple_rets.append(int(simple_heap_push(pri, ind, np.float32(d), np.int32(idx))))
out.append(carr("simple_push_rets", simple_rets, "std::int32_t"))
out.append(carr("simple_push_final_ind", ind, "std::int32_t"))
out.append(carr("simple_push_final_dist", pri, "float"))

# ---------------------------------------------------------------- deheap_sort
rsd = np.random.RandomState(7)
dh_ind = rsd.randint(0, 100, size=(4, 7)).astype(np.int32)
dh_dist = rsd.uniform(0, 10, size=(4, 7)).astype(np.float32)
dh_ind_in = dh_ind.copy()
dh_dist_in = dh_dist.copy()
deheap_sort(dh_ind, dh_dist)
out.append("// deheap_sort on a 4x7 array pair (input need not be a valid heap)")
out.append(carr("deheap_ind_in", dh_ind_in, "std::int32_t"))
out.append(carr("deheap_dist_in", dh_dist_in, "float"))
out.append(carr("deheap_ind_out", dh_ind, "std::int32_t"))
out.append(carr("deheap_dist_out", dh_dist, "float"))

# ------------------------------------------------------- new_build_candidates
# Fixed 10-vertex, 4-neighbor graph with mixed flags; max_candidates=3,
# n_threads=1, fixed rng_state.
g = make_heap(10, 4)
rsc = np.random.RandomState(3)
for i in range(10):
    picks = rsc.choice([j for j in range(10) if j != i], size=4, replace=False)
    g[0][i] = picks.astype(np.int32)
    g[1][i] = np.sort(rsc.uniform(0.1, 2.0, 4)).astype(np.float32)[::-1]
    g[2][i] = (rsc.uniform(size=4) < 0.6).astype(np.uint8)
# one unfilled slot
g[0][9, 3] = -1
g[2][9, 3] = 0
cand_graph_ind = g[0].copy()
cand_graph_flag_in = g[2].copy()
cand_rng = np.array([1234567, -7654321, 42424242], dtype=np.int64)
new_c, old_c = new_build_candidates(g, 3, cand_rng.copy(), 1)
out.append("// new_build_candidates: 10x4 graph, max_candidates=3, n_threads=1")
out.append(carr("cand_graph_ind", cand_graph_ind, "std::int32_t"))
out.append(carr("cand_graph_flag_in", cand_graph_flag_in, "std::int32_t"))
out.append(carr("cand_rng_state", cand_rng, "std::int64_t"))
out.append(carr("cand_new", new_c, "std::int32_t"))
out.append(carr("cand_old", old_c, "std::int32_t"))
out.append(carr("cand_graph_flag_out", g[2], "std::int32_t"))

# ------------------------------------------------------------ RP-tree splits
rsp = np.random.RandomState(5)
split_data = rsp.uniform(-1.0, 1.0, size=(12, 4)).astype(np.float32)
split_indices = np.arange(12, dtype=np.int32)

st = np.array([987654321, -123456789, 555555555], dtype=np.int64)
st_e = st.copy()
el, er, ehp, eoff = rp_trees.euclidean_random_projection_split(
    split_data, split_indices, st_e
)
out.append("// euclidean_random_projection_split on split_data (12x4), fixed rng state")
out.append(carr("split_data", split_data, "float"))
out.append(carr("split_rng_state", st, "std::int64_t"))
out.append(carr("esplit_left", el, "std::int32_t"))
out.append(carr("esplit_right", er, "std::int32_t"))
out.append(carr("esplit_hyperplane", ehp, "float"))
out.append("static const float esplit_offset = %s;" % fmt_float(eoff))
out.append(carr("esplit_rng_after", st_e, "std::int64_t"))

st_a = st.copy()
al, ar, ahp, aoff = rp_trees.angular_random_projection_split(
    split_data, split_indices, st_a
)
out.append(carr("asplit_left", al, "std::int32_t"))
out.append(carr("asplit_right", ar, "std::int32_t"))
out.append(carr("asplit_hyperplane", ahp, "float"))
out.append("static const float asplit_offset = %s;" % fmt_float(aoff))
out.append(carr("asplit_rng_after", st_a, "std::int64_t"))

# ------------------------------------------------------------- RP-tree leaves
rst = np.random.RandomState(11)
tree_data = rst.uniform(0.0, 1.0, size=(100, 4)).astype(np.float32)
tree_rng = np.array([-2091788700, 121212121, 987001234], dtype=np.int64)

t_e = rp_trees.make_dense_tree(tree_data, tree_rng.copy(), 15, False, 200)
leaves_e = rp_trees.get_leaves_from_tree(t_e, np.int32(t_e.leaf_size))
out.append("// make_dense_tree leaves: 100x4 data, leaf_size=15, euclidean")
out.append(carr("tree_data", tree_data, "float"))
out.append(carr("tree_rng_state", tree_rng, "std::int64_t"))
out.append("static const std::int64_t etree_n_leaves = %d;" % leaves_e.shape[0])
out.append("static const std::int64_t etree_leaf_width = %d;" % leaves_e.shape[1])
out.append(carr("etree_leaves", leaves_e, "std::int32_t"))

t_a = rp_trees.make_dense_tree(tree_data, tree_rng.copy(), 15, True, 200)
leaves_a = rp_trees.get_leaves_from_tree(t_a, np.int32(t_a.leaf_size))
out.append("static const std::int64_t atree_n_leaves = %d;" % leaves_a.shape[0])
out.append("static const std::int64_t atree_leaf_width = %d;" % leaves_a.shape[1])
out.append(carr("atree_leaves", leaves_a, "std::int32_t"))

# ----------------------------------------------------- end-to-end test data
# Small dataset (fully convergent) and a medium one for recall thresholds.
rsx = np.random.RandomState(1234)
small_data = rsx.uniform(0.0, 1.0, size=(80, 4)).astype(np.float32)
med_data = rsx.uniform(0.0, 1.0, size=(600, 8)).astype(np.float32)
out.append("static const std::int64_t small_n = 80;")
out.append("static const std::int64_t small_dim = 4;")
out.append(carr("small_data", small_data, "float"))
out.append("static const std::int64_t med_n = 600;")
out.append("static const std::int64_t med_dim = 8;")
out.append(carr("med_data", med_data, "float"))

out.append("}  // namespace golden_nn")
print("\n".join(out))
