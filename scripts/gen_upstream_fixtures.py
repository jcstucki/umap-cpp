def corrected(dm, rules):
    dm = dm.copy()
    for r in rules:
        if r == "zero":
            dm[np.where(~np.isfinite(dm))] = 0.0
        elif r == "one":
            dm[np.where(~np.isfinite(dm))] = 1.0
        elif r == "zerodiag_1011":
            dm[10, 11] = 0.0
            dm[11, 10] = 0.0
    return dm


