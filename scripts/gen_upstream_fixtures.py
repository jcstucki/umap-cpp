def fmt_f64(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<double>::quiet_NaN()"
    if np.isinf(v):
        return "std::numeric_limits<double>::infinity()" if v > 0 else \
            "-std::numeric_limits<double>::infinity()"
    return repr(v)


def fmt_f32(v):
    f = np.float32(v)
    if np.isnan(f):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(f):
        return "std::numeric_limits<float>::infinity()" if f > 0 else \
            "-std::numeric_limits<float>::infinity()"
    return np.format_float_positional(f, unique=True, trim="0") + "f"


class Header:
    def __init__(self, path, ns, doc):
        self.lines = [
            "// Auto-generated by scripts/gen_upstream_fixtures.py -- do not edit.",
            "// " + doc,
            "#pragma once",
            "#include <cstdint>",
            "#include <limits>",
            "",
            "namespace %s {" % ns,
            "",
        ]
        self.path = path
        self.ns = ns

    def comment(self, text):
        self.lines.append("// " + text)

    def scalar(self, name, v, ctype="double"):
        self.lines.append("static const %s %s = %s;" % (ctype, name, fmt_f64(v) if ctype == "double" else str(v)))

    def arr(self, name, a, ctype):
        a = np.asarray(a)
        flat = a.ravel()
        if ctype == "double":
            body = ", ".join(fmt_f64(v) for v in flat)
        elif ctype == "float":
            body = ", ".join(fmt_f32(v) for v in flat)
        else:
            body = ", ".join(str(int(v)) for v in flat)
        self.lines.append("static const %s %s[] = {%s};" % (ctype, name, body))

    def write(self):
        self.lines += ["", "}  // namespace %s" % self.ns, ""]
        with open(self.path, "w") as f:
            f.write("\n".join(self.lines))
        print("wrote %s (%d KB)" % (self.path, len("\n".join(self.lines)) // 1024))


