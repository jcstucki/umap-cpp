def disconnected(num_isolates, shape, p, seed):
    rs = np.random.RandomState(seed)
    data = rs.choice(a=[False, True], size=shape, p=p)
    data = np.vstack([data, np.zeros((num_isolates, shape[1]), dtype="bool")])
    new_columns = np.zeros((num_isolates + shape[0], num_isolates), dtype="bool")
    for i in range(num_isolates):
        new_columns[shape[0] + i, i] = True
    return np.hstack([data, new_columns])


