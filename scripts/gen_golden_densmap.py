#!/usr/bin/env python3
"""Generate golden values for the densMAP / output_metric / metric_kwds tests
(tests/golden_densmap.hpp).

Runs the *actual* reference UMAP (reference/umap + reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1, seeded random_state so upstream forces the
serial code paths) end to end. All fits use init="random" and explicit a/b
(find_ab_params parity is only ~1e-7) so the small-data cases are fully
deterministic and the C++ port can aim for bit-exactness.

Cases:
  dm) 200x5 blobs, densmap=True + output_dens=True, small-data branch.
      Captures the SGD inputs (init / rng_state / head / tail / eps), the
      densmap_kwds arrays (mu_sum, R), n_epochs (densMAP default 500+200),
      the final embedding and rad_orig_ / rad_emb_.
  dd) same X, output_dens=True only (densmap=False): embedding must equal the
      plain fit; rad_orig_ / rad_emb_ captured.
  dh) 150x5 blobs, output_metric="haversine" (n_components=2): generic-output
      SGD golden for fit AND transform (20 held-out queries).
  mk) 200x5 blobs, metric="minkowski", metric_kwds={"p": 3}: small-data
      pairwise path golden for fit AND transform (30 queries).
  ms) 200x5 blobs, metric="seuclidean", metric_kwds={"sigma": var}: small-data
      pairwise path with an array-valued kwd.
  mn) 60x5 blobs, metric="minkowski" p=3, force_approximation_algorithm=True:
      NN-descent generic-metric (no fast alternative) path; captures the kNN
      graph, fit embedding and transform (20 queries).

Usage:
    NUMBA_NUM_THREADS=1 "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python \
        scripts/gen_golden_densmap.py > tests/golden_densmap.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402

import umap.umap_ as um  # noqa: E402


# ------------------------------------------------------------- capture patch
captured = []
_orig_opt_euc = um.optimize_layout_euclidean
_orig_opt_gen = um.optimize_layout_generic


def _capturing_opt_euclidean(head_embedding, tail_embedding, head, tail,
                             n_epochs, n_vertices, epochs_per_sample, a, b,
                             rng_state, *args, **kwargs):
    cap = {
        "kind": "euclidean",
        "init": head_embedding.copy(),
        "rng_state": rng_state.copy(),
        "n_epochs": n_epochs,
        "head": head.copy(),
        "tail": tail.copy(),
        "eps": epochs_per_sample.copy(),
    }
    dk = kwargs.get("densmap_kwds")
    if kwargs.get("densmap") and dk is not None:
        cap["mu_sum"] = dk["mu_sum"].copy()
        cap["R"] = dk["R"].copy()
    captured.append(cap)
    return _orig_opt_euc(head_embedding, tail_embedding, head, tail, n_epochs,
                         n_vertices, epochs_per_sample, a, b, rng_state,
                         *args, **kwargs)


def _capturing_opt_generic(head_embedding, tail_embedding, head, tail,
                           n_epochs, n_vertices, epochs_per_sample, a, b,
                           rng_state, *args, **kwargs):
    captured.append({
        "kind": "generic",
        "init": head_embedding.copy(),
        "rng_state": rng_state.copy(),
        "n_epochs": n_epochs,
        "head": head.copy(),
        "tail": tail.copy(),
        "eps": epochs_per_sample.copy(),
    })
    return _orig_opt_gen(head_embedding, tail_embedding, head, tail, n_epochs,
                         n_vertices, epochs_per_sample, a, b, rng_state,
                         *args, **kwargs)


um.optimize_layout_euclidean = _capturing_opt_euclidean
um.optimize_layout_generic = _capturing_opt_generic


# ------------------------------------------------------------------ emitters
def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_densmap.py"
           " -- do not edit by hand.")
out.append("// Golden values computed with the reference UMAP in"
           " reference/umap")
out.append("// (+ reference/pynndescent), NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_densmap {")


def make_blobs(rng, n, dim, centers, std):
    pts = []
    per = n // len(centers)
    for ci, c in enumerate(centers):
        cnt = per if ci < len(centers) - 1 else n - per * (len(centers) - 1)
        pts.append(rng.randn(cnt, dim) * std + np.asarray(c))
    return np.vstack(pts).astype(np.float32)


def emit_fit(prefix, X, model, queries=None, dens=False, sgd_stage=True):
    fit_capture_idx = len(captured)
    emb = model.fit_transform(X)
    if isinstance(emb, tuple):  # output_dens: (embedding, rad_orig, rad_emb)
        emb = emb[0]
    cap = captured[fit_capture_idx]
    n, dim = X.shape
    out.append("// ---- %s: %dx%d, metric=%s, output_metric=%s, densmap=%s,"
               " output_dens=%s" % (
                   prefix, n, dim, model.metric, model.output_metric,
                   model.densmap, model.output_dens))
    out.append("static const std::int64_t %s_n = %d;" % (prefix, n))
    out.append("static const std::int64_t %s_dim = %d;" % (prefix, dim))
    out.append(carr("%s_X" % prefix, X))
    if sgd_stage:
        out.append(carr("%s_fit_init" % prefix, cap["init"]))
        out.append(carr("%s_fit_rng_state" % prefix, cap["rng_state"],
                        "std::int64_t"))
        out.append(carr("%s_fit_head" % prefix, cap["head"], "std::int32_t"))
        out.append(carr("%s_fit_tail" % prefix, cap["tail"], "std::int32_t"))
        out.append(carr("%s_fit_eps" % prefix, cap["eps"], "double"))
        out.append("static const std::int64_t %s_fit_n_edges = %d;" % (
            prefix, len(cap["head"])))
    out.append("static const int %s_fit_n_epochs = %d;" % (prefix,
                                                           cap["n_epochs"]))
    if dens and "mu_sum" in cap:
        out.append(carr("%s_mu_sum" % prefix, cap["mu_sum"]))
        out.append(carr("%s_R" % prefix, cap["R"]))
    out.append(carr("%s_embedding" % prefix, emb))
    if model.output_dens:
        out.append(carr("%s_rad_orig" % prefix, model.rad_orig_))
        out.append(carr("%s_rad_emb" % prefix, model.rad_emb_))
    if queries is not None:
        temb = model.transform(queries)
        out.append("static const std::int64_t %s_nq = %d;" % (
            prefix, queries.shape[0]))
        out.append(carr("%s_queries" % prefix, queries))
        out.append(carr("%s_t_embedding" % prefix, temb))
    out.append("")
    return emb


centers5 = [[0.0] * 5, [2.0, 1.5, 0.0, -1.0, 0.5], [-1.5, 2.0, 1.0, 0.5, -1.0]]
ab_a, ab_b = um.find_ab_params(1.0, 0.1)
out.append("static const double g_a = %.17g;" % ab_a)
out.append("static const double g_b = %.17g;" % ab_b)
out.append("")

Xc = make_blobs(np.random.RandomState(4321), 200, 5, centers5, 1.0)

# ---- dm: densmap + output_dens, small-data branch, random init
model_dm = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                   densmap=True, output_dens=True)
emit_fit("dm", Xc, model_dm, dens=True)
assert captured[-1]["n_epochs"] == 700, captured[-1]["n_epochs"]

# training-data transform hash shortcut still works for densMAP models,
# new data raises NotImplementedError
np.testing.assert_array_equal(model_dm.transform(Xc), model_dm.embedding_)
try:
    model_dm.transform(Xc[:5] + 1.0)
    raise AssertionError("densmap transform should have raised")
except NotImplementedError:
    pass

# ---- dd: output_dens only (embedding must match the plain fit)
model_dd = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                   output_dens=True)
emb_dd = emit_fit("dd", Xc, model_dd)
model_pl = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b)
emb_pl = model_pl.fit_transform(Xc)
np.testing.assert_array_equal(np.asarray(emb_dd), np.asarray(emb_pl))
out.append("// dd embedding is bitwise identical to the plain"
           " (no output_dens) fit in Python")
out.append("")

# ---- dh: output_metric="haversine" fit + transform (generic SGD)
Xh = make_blobs(np.random.RandomState(7), 150, 5, centers5, 1.0)
Qh = make_blobs(np.random.RandomState(77), 20, 5, centers5, 1.0)
model_dh = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                   output_metric="haversine", n_components=2)
emit_fit("dh", Xh, model_dh, queries=Qh)
assert captured[-1]["kind"] == "generic"

# ---- mk: metric="minkowski" p=3, small-data pairwise path
Qc = make_blobs(np.random.RandomState(99), 30, 5, centers5, 1.0)
model_mk = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                   metric="minkowski", metric_kwds={"p": 3.0})
emit_fit("mk", Xc, model_mk, queries=Qc, sgd_stage=False)

# ---- ms: metric="seuclidean" with an array-valued kwd
sigma = Xc.astype(np.float64).var(axis=0)
out.append(carr("ms_sigma", sigma, "double"))
model_ms = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                   metric="seuclidean", metric_kwds={"sigma": sigma})
emit_fit("ms", Xc, model_ms, sgd_stage=False)

# ---- mn: minkowski p=3 through NN-descent (generic-metric hook)
Xn = make_blobs(np.random.RandomState(1234), 60, 5, centers5, 1.0)
Qn = make_blobs(np.random.RandomState(55), 20, 5, centers5, 1.0)
model_mn = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                   metric="minkowski", metric_kwds={"p": 3.0},
                   force_approximation_algorithm=True)
emit_fit("mn", Xn, model_mn, queries=Qn, sgd_stage=False)
out.append("static const std::int64_t mn_k = %d;" % model_mn._n_neighbors)
out.append(carr("mn_knn_indices", model_mn._knn_indices, "std::int32_t"))
out.append(carr("mn_knn_dists", model_mn._knn_dists))
out.append("")

out.append("}  // namespace golden_densmap")
print("\n".join(out))
