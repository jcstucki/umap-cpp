#!/usr/bin/env python3
"""Generate golden values for the C++ query-path port (tests/golden_query.hpp).

Fits the *actual* reference pynndescent NNDescent (reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1) with the exact parameters UMAP's
nearest_neighbors uses, calls prepare(), and queries held-out points --
goldening both the prepared artifacts (_vertex_order, _search_graph,
_search_forest[0], _min_distance, warmed search_rng_state) and the query
results, so the C++ PreparedIndex can be validated stage by stage.

Usage:
    NUMBA_NUM_THREADS=1 "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python scripts/gen_golden_query.py > tests/golden_query.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))

import numpy as np  # noqa: E402

from pynndescent import NNDescent  # noqa: E402


def fmt_float(v):
    v = float(v)
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "std::int8_t", "std::uint8_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_query.py -- do not edit by hand.")
out.append("// Golden values computed with the reference pynndescent in reference/pynndescent")
out.append("// (NUMBA_NUM_THREADS=1).")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_query {")


def run_case(tag, train, queries, metric, k=10, epsilon=0.1, seed=42,
             n_neighbors=10, umap_epsilon=None):
    n = train.shape[0]
    # umap_.py::nearest_neighbors "hacked values" + fixed max_candidates
    n_trees = min(64, 5 + int(round(n ** 0.5 / 20.0)))
    n_iters = max(5, int(round(np.log2(n))))
    index = NNDescent(
        train,
        n_neighbors=n_neighbors,
        metric=metric,
        random_state=seed,
        n_trees=n_trees,
        n_iters=n_iters,
        max_candidates=60,
        low_memory=True,
        n_jobs=None,
        verbose=False,
        compressed=False,
    )
    index.prepare()
    ind, dist = index.query(queries, k=k, epsilon=epsilon)

    tree = index._search_forest[0]
    out.append("// ---- %s: %dx%d train, %d queries, metric=%s, k=%d, eps=%s, seed=%d"
               % (tag, n, train.shape[1], queries.shape[0], metric, k, epsilon, seed))
    out.append("static const std::int64_t %s_n = %d;" % (tag, n))
    out.append("static const std::int64_t %s_dim = %d;" % (tag, train.shape[1]))
    out.append("static const std::int64_t %s_nq = %d;" % (tag, queries.shape[0]))
    out.append(carr("%s_train" % tag, train, "float"))
    out.append(carr("%s_queries" % tag, queries, "float"))
    out.append(carr("%s_search_rng_state" % tag, index.search_rng_state,
                    "std::int64_t"))
    out.append(carr("%s_vertex_order" % tag, index._vertex_order,
                    "std::int32_t"))
    out.append(carr("%s_graph_indptr" % tag, index._search_graph.indptr,
                    "std::int32_t"))
    out.append(carr("%s_graph_indices" % tag, index._search_graph.indices,
                    "std::int32_t"))
    out.append("static const float %s_min_distance = %s;"
               % (tag, fmt_float(index._min_distance)))
    out.append("static const std::int64_t %s_tree_n_nodes = %d;"
               % (tag, tree.children.shape[0]))
    out.append(carr("%s_tree_children" % tag, tree.children, "std::int32_t"))
    out.append(carr("%s_tree_offsets" % tag, tree.offsets, "float"))
    out.append(carr("%s_tree_hyperplanes" % tag, tree.hyperplanes, "float"))
    out.append(carr("%s_query_ind" % tag, ind, "std::int32_t"))
    out.append(carr("%s_query_dist" % tag, dist, "float"))

    # UMAP's transform() epsilon: 0.24 for angular trees, 0.12 otherwise
    if umap_epsilon is not None:
        ind_u, dist_u = index.query(queries, k=k, epsilon=umap_epsilon)
        out.append("static const float %s_umap_epsilon = %s;"
                   % (tag, fmt_float(umap_epsilon)))
        out.append(carr("%s_query_ind_umap_eps" % tag, ind_u, "std::int32_t"))
        out.append(carr("%s_query_dist_umap_eps" % tag, dist_u, "float"))
    out.append("")


rs = np.random.RandomState(1234)
train_e = rs.uniform(-1.0, 1.0, size=(200, 6)).astype(np.float32)
query_e = rs.uniform(-1.0, 1.0, size=(20, 6)).astype(np.float32)
run_case("euc", train_e, query_e, "euclidean", umap_epsilon=0.12)

rs = np.random.RandomState(5678)
train_c = rs.normal(0.0, 1.0, size=(150, 8)).astype(np.float32)
query_c = rs.normal(0.0, 1.0, size=(20, 8)).astype(np.float32)
run_case("cos", train_c, query_c, "cosine", umap_epsilon=0.24)

out.append("}  // namespace golden_query")
print("\n".join(out))
