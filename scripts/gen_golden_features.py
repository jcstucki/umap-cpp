#!/usr/bin/env python3
"""Generate golden values for the Phase 1b feature-bundle tests
(tests/golden_features.hpp): metric="precomputed", precomputed_knn,
unique=True, init as ndarray / "pca", n_epochs lists, transform_mode="graph"
and finite disconnection_distance.

Runs the *actual* reference UMAP (reference/umap + reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1, seeded random_state so upstream forces the
serial code paths). All cases use init="random" (or a user array) plus an
explicit a/b so the deterministic small-data/standard paths are bit-exact in
C++, except the PCA-init case which is validated at documented tolerance
(sklearn runs float32 LAPACK, the port runs float64 Eigen).

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python \
        scripts/gen_golden_features.py > tests/golden_features.hpp
"""
import os
import sys
import warnings

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402

import umap.umap_ as um  # noqa: E402
import umap.distances as dist  # noqa: E402
from sklearn.metrics import pairwise_distances  # noqa: E402

warnings.filterwarnings("ignore")

# ------------------------------------------------------------- capture patch
captured = []
_orig_opt = um.optimize_layout_euclidean


def _capturing_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                   n_vertices, epochs_per_sample, a, b, rng_state, *args,
                   **kwargs):
    captured.append({
        "init": head_embedding.copy(),
        "rng_state": rng_state.copy(),
        "n_epochs": n_epochs,
        "head": head.copy(),
        "tail": tail.copy(),
        "eps": epochs_per_sample.copy(),
    })
    return _orig_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                     n_vertices, epochs_per_sample, a, b, rng_state, *args,
                     **kwargs)


um.optimize_layout_euclidean = _capturing_opt


# ------------------------------------------------------------------ emitters
def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_features.py -- do not edit by hand.")
out.append("// Golden values computed with the reference UMAP in reference/umap")
out.append("// (+ reference/pynndescent), NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_features {")


def make_blobs(rng, n, dim, centers, std):
    pts = []
    per = n // len(centers)
    for ci, c in enumerate(centers):
        cnt = per if ci < len(centers) - 1 else n - per * (len(centers) - 1)
        pts.append(rng.randn(cnt, dim) * std + np.asarray(c))
    return np.vstack(pts).astype(np.float32)


def emit_capture(prefix, cap):
    out.append(carr("%s_init" % prefix, cap["init"]))
    out.append(carr("%s_rng_state" % prefix, cap["rng_state"], "std::int64_t"))
    n_ep = cap["n_epochs"]
    if isinstance(n_ep, list):
        n_ep = max(n_ep)
    out.append("static const int %s_n_epochs = %d;" % (prefix, n_ep))
    out.append("static const std::int64_t %s_n_edges = %d;" % (
        prefix, len(cap["head"])))
    out.append(carr("%s_head" % prefix, cap["head"], "std::int32_t"))
    out.append(carr("%s_tail" % prefix, cap["tail"], "std::int32_t"))
    out.append(carr("%s_eps" % prefix, cap["eps"], "double"))


def emit_csr(prefix, csr):
    csr = csr.tocsr()
    csr.sort_indices()
    out.append("static const std::int64_t %s_nrows = %d;" % (prefix, csr.shape[0]))
    out.append("static const std::int64_t %s_ncols = %d;" % (prefix, csr.shape[1]))
    out.append(carr("%s_indptr" % prefix, csr.indptr, "std::int32_t"))
    out.append(carr("%s_indices" % prefix, csr.indices, "std::int32_t"))
    out.append(carr("%s_data" % prefix, csr.data))


ab_a, ab_b = um.find_ab_params(1.0, 0.1)
out.append("static const double ab_a = %.17g;" % ab_a)
out.append("static const double ab_b = %.17g;" % ab_b)
out.append("")

centers5 = [[0.0] * 5, [2.0, 1.5, 0.0, -1.0, 0.5], [-1.5, 2.0, 1.0, 0.5, -1.0]]
centers6 = [[0.0] * 6, [2.5, 1.0, -1.0, 0.5, 1.5, 0.0],
            [-1.0, 2.0, 1.5, -0.5, 0.0, 1.0]]

# ===== fp: metric="precomputed", small-data branch (deterministic) ==========
Xp = make_blobs(np.random.RandomState(11), 90, 6, centers6, 0.9)
Dp = pairwise_distances(Xp.astype(np.float64)).astype(np.float32)
Qp = make_blobs(np.random.RandomState(12), 20, 6, centers6, 0.9)
QDp = pairwise_distances(Qp.astype(np.float64),
                         Xp.astype(np.float64)).astype(np.float32)

model_p = um.UMAP(metric="precomputed", init="random", random_state=42,
                  a=ab_a, b=ab_b)
i0 = len(captured)
emb_p = model_p.fit_transform(Dp)
out.append("// ---- fp: metric='precomputed', 90x90, small data, init=random")
out.append("static const std::int64_t fp_n = %d;" % Dp.shape[0])
out.append(carr("fp_D", Dp))
emit_capture("fp_fit", captured[i0])
out.append(carr("fp_embedding", emb_p))
i1 = len(captured)
temb_p = model_p.transform(QDp)
out.append("static const std::int64_t fp_nq = %d;" % QDp.shape[0])
out.append(carr("fp_QD", QDp))
emit_capture("fp_t", captured[i1])
out.append(carr("fp_t_embedding", temb_p))
out.append("")

# ===== fdisc: finite disconnection_distance, small data (deterministic) =====
# Two isolated outliers far from everything (and from each other) plus a
# borderline pair; disconnection_distance removes their edges entirely.
Xd = make_blobs(np.random.RandomState(21), 80, 5, centers5, 0.8)
Xd[78] = np.asarray([60.0, 60.0, 60.0, 60.0, 60.0], dtype=np.float32)
Xd[79] = np.asarray([-60.0, -60.0, 60.0, -60.0, 60.0], dtype=np.float32)
dd_val = 30.0
model_d = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                  disconnection_distance=dd_val)
i0 = len(captured)
emb_d = model_d.fit_transform(Xd)
# Replicate the small-data branch's edge-removal count.
dmat_d = pairwise_distances(Xd, metric=dist.named_distances["euclidean"])
edges_removed_d = int((dmat_d >= dd_val).sum())
verts_d = int((np.array(model_d.graph_.sum(axis=1)).flatten() == 0).sum())
out.append("// ---- fdisc: disconnection_distance=%g, 80x5, small data" % dd_val)
out.append("static const std::int64_t fdisc_n = %d;" % Xd.shape[0])
out.append("static const std::int64_t fdisc_dim = %d;" % Xd.shape[1])
out.append("static const double fdisc_dd = %.17g;" % dd_val)
out.append(carr("fdisc_X", Xd))
out.append("static const std::int64_t fdisc_edges_removed = %d;" % edges_removed_d)
out.append("static const std::int64_t fdisc_vertices_disconnected = %d;" % verts_d)
emit_capture("fdisc_fit", captured[i0])
out.append(carr("fdisc_embedding", emb_d))
# transform with the same disconnection distance: neighbours past dd get
# pruned (indices -> -1) before the membership strengths.
Qd = make_blobs(np.random.RandomState(22), 15, 5, centers5, 0.8)
Qd[14] = np.asarray([55.0, -55.0, 55.0, 55.0, -55.0], dtype=np.float32)
i1 = len(captured)
temb_d = model_d.transform(Qd)
out.append("static const std::int64_t fdisc_nq = %d;" % Qd.shape[0])
out.append(carr("fdisc_Q", Qd))
emit_capture("fdisc_t", captured[i1])
out.append(carr("fdisc_t_embedding", temb_d))
out.append("")

# ===== fpk: precomputed_knn (n < 4096 forces the approximation branch) ======
Xk = make_blobs(np.random.RandomState(31), 180, 5, centers5, 1.0)
from sklearn.neighbors import NearestNeighbors  # noqa: E402

nn = NearestNeighbors(n_neighbors=15).fit(Xk.astype(np.float64))
kd, ki = nn.kneighbors(Xk.astype(np.float64))
knn_dists_k = kd.astype(np.float32)
knn_indices_k = ki.astype(np.int32)
model_k = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                  precomputed_knn=(knn_indices_k, knn_dists_k))
i0 = len(captured)
emb_k = model_k.fit_transform(Xk)
assert model_k._small_data is False
out.append("// ---- fpk: precomputed_knn (k=15), 180x5, forced standard branch")
out.append("static const std::int64_t fpk_n = %d;" % Xk.shape[0])
out.append("static const std::int64_t fpk_dim = %d;" % Xk.shape[1])
out.append("static const std::int64_t fpk_k = %d;" % knn_indices_k.shape[1])
out.append(carr("fpk_X", Xk))
out.append(carr("fpk_knn_indices", knn_indices_k, "std::int32_t"))
out.append(carr("fpk_knn_dists", knn_dists_k))
emit_capture("fpk_fit", captured[i0])
out.append(carr("fpk_embedding", emb_k))
out.append("")

# fpk2: wider-than-n_neighbors arrays on small data: the upstream elif chain
# sets force_approximation_algorithm and *skips* the column pruning, so the
# fuzzy set runs on all 20 columns with k = n_neighbors = 15.
nn2 = NearestNeighbors(n_neighbors=20).fit(Xk.astype(np.float64))
kd2, ki2 = nn2.kneighbors(Xk.astype(np.float64))
knn_dists_k2 = kd2.astype(np.float32)
knn_indices_k2 = ki2.astype(np.int32)
model_k2 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
                   precomputed_knn=(knn_indices_k2, knn_dists_k2))
i0 = len(captured)
emb_k2 = model_k2.fit_transform(Xk)
assert model_k2._knn_dists.shape[1] == 20  # pruning skipped
out.append("// ---- fpk2: precomputed_knn wider than n_neighbors (k=20)")
out.append("static const std::int64_t fpk2_k = %d;" % knn_indices_k2.shape[1])
out.append(carr("fpk2_knn_indices", knn_indices_k2, "std::int32_t"))
out.append(carr("fpk2_knn_dists", knn_dists_k2))
emit_capture("fpk2_fit", captured[i0])
out.append(carr("fpk2_embedding", emb_k2))
out.append("")

# ===== fu: unique=True (row dedup + inverse mapping, deterministic) =========
Xu_base = make_blobs(np.random.RandomState(41), 100, 4,
                     [[0.0] * 4, [2.0, -1.0, 1.5, 0.5], [-1.5, 1.0, -1.0, 2.0]],
                     0.8)
dup_src = np.random.RandomState(42).randint(0, 100, 40)
Xu = np.vstack([Xu_base, Xu_base[dup_src]]).astype(np.float32)
perm_u = np.random.RandomState(43).permutation(Xu.shape[0])
Xu = Xu[perm_u]
model_u = um.UMAP(unique=True, init="random", random_state=42, a=ab_a, b=ab_b)
i0 = len(captured)
emb_u = model_u.fit_transform(Xu)
uniq_index = np.unique(Xu, axis=0, return_index=True)[1]
out.append("// ---- fu: unique=True, 140x4 with 40 duplicated rows")
out.append("static const std::int64_t fu_n = %d;" % Xu.shape[0])
out.append("static const std::int64_t fu_dim = %d;" % Xu.shape[1])
out.append("static const std::int64_t fu_n_unique = %d;" % len(uniq_index))
out.append(carr("fu_X", Xu))
out.append(carr("fu_unique_index", uniq_index, "std::int64_t"))
out.append(carr("fu_unique_inverse", model_u._unique_inverse_, "std::int64_t"))
emit_capture("fu_fit", captured[i0])
out.append(carr("fu_embedding", emb_u))
out.append("")

# ===== fi: init as a user ndarray (KDTree jitter branch, deterministic) =====
Xi = make_blobs(np.random.RandomState(51), 150, 5, centers5, 1.0)
init_dup = np.random.RandomState(52).uniform(-10, 10, (150, 2)).astype(np.float32)
init_dup[30] = init_dup[70]  # exact duplicate rows -> jitter branch
init_dup[31] = init_dup[70]
model_i = um.UMAP(init=init_dup, random_state=42, a=ab_a, b=ab_b)
i0 = len(captured)
emb_i = model_i.fit_transform(Xi)
out.append("// ---- fi: init=user ndarray with duplicate rows (jitter branch)")
out.append("static const std::int64_t fi_n = %d;" % Xi.shape[0])
out.append("static const std::int64_t fi_dim = %d;" % Xi.shape[1])
out.append(carr("fi_X", Xi))
out.append(carr("fi_init_array", init_dup))
emit_capture("fi_fit", captured[i0])
out.append(carr("fi_embedding", emb_i))

# fi2: no duplicate rows -> init passes through untouched (no rng draws).
init_nodup = np.random.RandomState(53).uniform(-10, 10, (150, 2)).astype(np.float32)
assert np.unique(init_nodup, axis=0).shape[0] == 150
model_i2 = um.UMAP(init=init_nodup, random_state=42, a=ab_a, b=ab_b)
i0 = len(captured)
emb_i2 = model_i2.fit_transform(Xi)
out.append("// ---- fi2: init=user ndarray without duplicates (passthrough)")
out.append(carr("fi2_init_array", init_nodup))
emit_capture("fi2_fit", captured[i0])
out.append(carr("fi2_embedding", emb_i2))
out.append("")

# ===== fpca: init="pca" (documented tolerance vs float32 LAPACK) ============
Xpca = make_blobs(np.random.RandomState(61), 120, 6, centers6, 1.0)
model_pca = um.UMAP(init="pca", random_state=42, a=ab_a, b=ab_b)
i0 = len(captured)
emb_pca = model_pca.fit_transform(Xpca)
out.append("// ---- fpca: init='pca', 120x6, small data")
out.append("static const std::int64_t fpca_n = %d;" % Xpca.shape[0])
out.append("static const std::int64_t fpca_dim = %d;" % Xpca.shape[1])
out.append(carr("fpca_X", Xpca))
emit_capture("fpca_fit", captured[i0])
out.append(carr("fpca_embedding", emb_pca))
out.append("")

# ===== fe: n_epochs as a list (embedding snapshots, deterministic) ==========
Xe = make_blobs(np.random.RandomState(71), 150, 5, centers5, 1.0)
epochs_list = [5, 50, 100]
model_e = um.UMAP(n_epochs=epochs_list, init="random", random_state=42,
                  a=ab_a, b=ab_b)
i0 = len(captured)
emb_e = model_e.fit_transform(Xe)
out.append("// ---- fe: n_epochs=%s (snapshots at listed epochs + final)" %
           epochs_list)
out.append("static const std::int64_t fe_n = %d;" % Xe.shape[0])
out.append("static const std::int64_t fe_dim = %d;" % Xe.shape[1])
out.append(carr("fe_epochs_list", epochs_list, "int"))
out.append("static const std::int64_t fe_epochs_list_len = %d;" % len(epochs_list))
out.append(carr("fe_X", Xe))
emit_capture("fe_fit", captured[i0])
out.append("static const std::int64_t fe_embedding_list_len = %d;" %
           len(model_e.embedding_list_))
for li, e in enumerate(model_e.embedding_list_):
    out.append(carr("fe_embedding_list_%d" % li, e))
out.append(carr("fe_embedding", emb_e))
out.append("")

# ===== fg: transform_mode="graph" ===========================================
Xg = make_blobs(np.random.RandomState(81), 130, 5, centers5, 1.0)
Qg = make_blobs(np.random.RandomState(82), 25, 5, centers5, 1.0)
model_g = um.UMAP(transform_mode="graph", random_state=42)
g_fit = model_g.fit_transform(Xg)
g_t = model_g.transform(Qg)
assert not hasattr(model_g, "embedding_") or model_g.embedding_ is None or True
out.append("// ---- fg: transform_mode='graph', 130x5 (+25 queries)")
out.append("static const std::int64_t fg_n = %d;" % Xg.shape[0])
out.append("static const std::int64_t fg_dim = %d;" % Xg.shape[1])
out.append("static const std::int64_t fg_nq = %d;" % Qg.shape[0])
out.append(carr("fg_X", Xg))
out.append(carr("fg_Q", Qg))
emit_csr("fg_graph", g_fit)
emit_csr("fg_t_graph", g_t)
out.append("")

out.append("}  // namespace golden_features")
print("\n".join(out))
print("// cases emitted: fp fdisc fpk fpk2 fu fi fi2 fpca fe fg",
      file=sys.stderr)
