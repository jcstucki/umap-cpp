#!/usr/bin/env python3
"""Generate golden values for the layout SGD tests from the reference Python UMAP.

Runs the *actual* reference implementation checked out at reference/umap
(numba-jitted; requires numpy/scipy/scikit-learn/numba/pynndescent/tqdm).

Usage:
    "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python scripts/gen_golden_layout.py > tests/golden_layout.hpp
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.environ.get("UMAP_REFERENCE", os.path.join(REPO, "reference", "umap"))
sys.path.insert(0, REF)

import numpy as np  # noqa: E402

from umap.layouts import clip, rdist, optimize_layout_euclidean  # noqa: E402
from umap.umap_ import (  # noqa: E402
    fuzzy_simplicial_set,
    find_ab_params,
    make_epochs_per_sample,
)


def fmt_float(v):
    s = "%.9g" % v
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="double", fmt="{:.17g}"):
    flat = np.asarray(values).ravel()
    if fmt == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    else:
        vals = ", ".join(fmt.format(v) for v in flat)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_layout.py -- do not edit by hand.")
out.append("// Golden values computed with the reference Python UMAP in reference/umap.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("")
out.append("namespace golden {")

# ------------------------------------------------------------------- clip
clip_in = np.array(
    [5.3, -7.25, 3.9999999, -4.0000001, 4.0, -4.0, 0.125, -0.0, 1e300, -1e300, 0.0],
    dtype=np.float64,
)
clip_out = np.array([clip(v) for v in clip_in], dtype=np.float64)
out.append(carr("clip_in", clip_in))
out.append(carr("clip_out", clip_out))

# ------------------------------------------------------------------- rdist
rng = np.random.RandomState(42)
rdist_x2 = rng.uniform(-12, 12, 2).astype(np.float32)
rdist_y2 = rng.uniform(-12, 12, 2).astype(np.float32)
rdist_x5 = rng.uniform(-3, 3, 5).astype(np.float32)
rdist_y5 = rng.uniform(-3, 3, 5).astype(np.float32)
out.append(carr("rdist_x2", rdist_x2, "float", "float"))
out.append(carr("rdist_y2", rdist_y2, "float", "float"))
out.append(carr("rdist_x5", rdist_x5, "float", "float"))
out.append(carr("rdist_y5", rdist_y5, "float", "float"))
out.append("static const float rdist_out2 = %s;" % fmt_float(rdist(rdist_x2, rdist_y2)))
out.append("static const float rdist_out5 = %s;" % fmt_float(rdist(rdist_x5, rdist_y5)))
# same-vector => exact zero
out.append("static const float rdist_out_same = %s;" % fmt_float(rdist(rdist_x5, rdist_x5)))

# ------------------------------------------- make_epochs_per_sample (exact)
meps_w = rng.uniform(0.0, 1.0, 20).astype(np.float32)
meps_w[3] = 0.0
meps_w[11] = 0.0
meps_w[7] = meps_w.max()  # duplicate of the max weight
out.append(carr("meps_weights", meps_w, "float", "float"))
out.append(carr("meps_out_500", make_epochs_per_sample(meps_w, 500)))
out.append(carr("meps_out_10", make_epochs_per_sample(meps_w, 10)))
out.append(carr("meps_out_1", make_epochs_per_sample(meps_w, 1)))

# ------------------------------------- shared small fuzzy graph (30 points)
n_pts, n_nbrs = 30, 6
X = rng.normal(size=(n_pts, 4)).astype(np.float32)
D = np.sqrt(((X[:, None, :].astype(np.float64) - X[None, :, :].astype(np.float64)) ** 2).sum(-1))
knn_indices = np.argsort(D, axis=1)[:, :n_nbrs].astype(np.int32)
knn_dists = np.take_along_axis(D, knn_indices.astype(np.int64), axis=1).astype(np.float32)
graph, _sigmas, _rhos = fuzzy_simplicial_set(
    X,
    n_nbrs,
    random_state=None,
    metric="euclidean",
    knn_indices=knn_indices,
    knn_dists=knn_dists,
)
graph = graph.tocsr()
graph.sort_indices()

a, b = find_ab_params(1.0, 0.1)
out.append("static const double layout_a = %.17g;" % a)
out.append("static const double layout_b = %.17g;" % b)

# The unfiltered graph CSR (input seam for the C++ glue test).
out.append("static const int graph_n = %d;" % n_pts)
out.append(carr("graph_indptr", graph.indptr, "int32_t", "{:d}"))
out.append(carr("graph_indices", graph.indices, "int32_t", "{:d}"))
out.append(carr("graph_data", graph.data, "float", "float"))

# --------------------- optimize_layout_euclidean golden (sequential numba)
g = graph.tocoo()
g.sum_duplicates()
n_epochs_direct = 50
g.data[g.data < (g.data.max() / float(n_epochs_direct))] = 0.0
g.eliminate_zeros()
eps = make_epochs_per_sample(g.data, n_epochs_direct)
head = g.row.astype(np.int32)
tail = g.col.astype(np.int32)

init = rng.uniform(-10.0, 10.0, (n_pts, 2)).astype(np.float32)
rng_state = np.array([-1704009011, 42, 2137459653], dtype=np.int64)

emb = init.copy()
final = optimize_layout_euclidean(
    emb,
    emb,
    head,
    tail,
    n_epochs_direct,
    n_pts,
    eps,
    a,
    b,
    rng_state.copy(),
    gamma=1.0,
    initial_alpha=1.0,
    negative_sample_rate=5.0,
    parallel=False,
    verbose=False,
    move_other=True,
)

out.append("static const int layout_n_epochs = %d;" % n_epochs_direct)
out.append(carr("layout_head", head, "int32_t", "{:d}"))
out.append(carr("layout_tail", tail, "int32_t", "{:d}"))
out.append(carr("layout_eps", eps))
out.append(carr("layout_init", init, "float", "float"))
out.append(carr("layout_rng_state", rng_state, "int64_t", "{:d}LL"))
out.append(carr("layout_final", final, "float", "float"))

# ------------- full simplicial_set_embedding glue golden (default n_epochs)
# Replicates the exact non-init glue of umap_.py::simplicial_set_embedding
# (euclidean output, densmap off) on the unfiltered graph above.
g2 = graph.tocoo()
g2.sum_duplicates()
default_epochs = 500 if g2.shape[0] <= 10000 else 200
n_epochs2 = default_epochs  # n_epochs=None path
if n_epochs2 > 10:
    g2.data[g2.data < (g2.data.max() / float(n_epochs2))] = 0.0
else:
    g2.data[g2.data < (g2.data.max() / float(default_epochs))] = 0.0
g2.eliminate_zeros()
eps2 = make_epochs_per_sample(g2.data, n_epochs2)
head2 = g2.row.astype(np.int32)
tail2 = g2.col.astype(np.int32)

init2 = rng.uniform(-7.0, 13.0, (n_pts, 2)).astype(np.float32)
rng_state2 = np.array([987654321, -246813579, 13579], dtype=np.int64)

emb2 = (
    10.0 * (init2 - np.min(init2, 0)) / (np.max(init2, 0) - np.min(init2, 0))
).astype(np.float32, order="C")
rescaled2 = emb2.copy()
final2 = optimize_layout_euclidean(
    emb2,
    emb2,
    head2,
    tail2,
    n_epochs2,
    n_pts,
    eps2,
    a,
    b,
    rng_state2.copy(),
    gamma=1.0,
    initial_alpha=1.0,
    negative_sample_rate=5.0,
    parallel=False,
    verbose=False,
    move_other=True,
)

out.append("static const int glue_n_epochs = %d;" % n_epochs2)
out.append(carr("glue_init", init2, "float", "float"))
out.append(carr("glue_rescaled_init", rescaled2, "float", "float"))
out.append(carr("glue_eps", eps2, "double"))
out.append(carr("glue_head", head2, "int32_t", "{:d}"))
out.append(carr("glue_rng_state", rng_state2, "int64_t", "{:d}LL"))
out.append(carr("glue_final", final2, "float", "float"))

out.append("}  // namespace golden")
print("\n".join(out))
