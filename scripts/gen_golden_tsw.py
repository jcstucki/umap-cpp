#!/usr/bin/env python3
"""Generate golden values for the tswspectral tests from the reference Python
UMAP (reference/umap) + scipy/sklearn.

Fixtures reproduced here:
  * test_spectral.py::test_tsw_spectral_init -- the (dense) random affinity
    matrix built from np.random.default_rng(42).standard_normal draws (PCG64,
    which the C++ port does not replicate, so the final graph is baked), plus
    dense-eigh reference eigenpairs of its normalized Laplacian and the
    upstream tswspectral_layout output.
      NOTE upstream skips this test for scipy >= 1.15 because eigsh's
      regular-mode which="SM" at tol=1e-4 misconverges there (this venv:
      scipy 1.18 -- spectral_layout lands ~0.63 away from the true
      eigenvectors while tswspectral_layout at tol=1e-8 matches dense eigh to
      ~1e-15). The C++ solvers (Spectra shift-invert / LOBPCG) converge
      tightly, i.e. they behave like the scipy in [1.10, 1.15) window where
      the upstream test is active, so the goldens anchor to the dense-eigh
      truth (== upstream tsw output).
  * test_spectral.py::test_ensure_fallback_to_random_on_spectral_failure --
    upstream draws u = np.random.random((1000, 100)) UNSEEDED; per the
    tests-port convention the C++ test bakes np.random.seed(777) (documented
    fixed seed) and regenerates u in-process via the bit-exact
    nnd::NumpyRandomState(777).random_sample() stream, so only spot-check
    values are emitted here (not 100k doubles).

Usage:
    /tmp/umapref-venv/bin/python scripts/gen_golden_tsw.py > tests/golden_tsw.hpp
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.environ.get("UMAP_REFERENCE", os.path.join(REPO, "reference", "umap"))
sys.path.insert(0, REF)

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402

from umap.spectral import tswspectral_layout  # noqa: E402


def carr(name, values, ctype="double", fmt="{:.17g}"):
    flat = np.asarray(values).ravel()
    if ctype.startswith("int"):
        vals = ", ".join(str(int(v)) for v in flat)
    else:
        vals = ", ".join(fmt.format(v) for v in flat)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


def normalized_laplacian(graph):
    """Exactly the construction in umap.spectral._spectral_layout."""
    g = np.asarray(graph, dtype=np.float64)
    sqrt_deg = np.sqrt(np.asarray(g.sum(axis=0)).squeeze())
    I = scipy.sparse.identity(g.shape[0], dtype=np.float64)
    D = scipy.sparse.spdiags(1.0 / sqrt_deg, 0, g.shape[0], g.shape[0])
    return np.asarray(I - D * g * D)


def main():
    out = []
    out.append("// Auto-generated by scripts/gen_golden_tsw.py -- do not edit by hand.")
    out.append("// Golden values computed with the reference Python UMAP + scipy/sklearn")
    out.append("// (scipy %s)." % scipy.__version__)
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace golden_tsw {")
    out.append("")

    # ---- test_tsw_spectral_init fixture -----------------------------------
    seed = 42
    rng = np.random.default_rng(seed=seed)
    n = 20
    graph = rng.standard_normal(n * n).reshape((n, n)) ** 2
    graph = graph.T * graph  # elementwise; symmetric dense affinity

    out.append("// test_tsw_spectral_init: dense affinity matrix from")
    out.append("// np.random.default_rng(42).standard_normal(400)**2, g = g.T * g")
    out.append("// (elementwise), baked because the C++ port has no PCG64.")
    out.append("static const int t1_n = %d;" % n)
    out.append(carr("t1_graph", graph))

    L = normalized_laplacian(graph)
    w, v = np.linalg.eigh(L)
    out.append("")
    out.append("// Smallest 4 eigenvalues of the normalized Laplacian (dense eigh);")
    out.append("// the eigengap after the trivial pair is comfortable, so up-to-sign")
    out.append("// eigenvector comparison is well-posed.")
    out.append(carr("t1_evals", w[:4]))
    out.append("// Dense-eigh eigenvectors 1..2 (row-major n x 2): the true spectral")
    out.append("// embedding both spectral_layout and tswspectral_layout must match")
    out.append("// up to per-column sign.")
    out.append(carr("t1_embed_eigh", v[:, 1:3]))

    tsw = tswspectral_layout(None, graph, 2, random_state=seed**2, tol=1e-8)
    err = max(
        min(np.abs(tsw[:, j] - v[:, 1 + j]).max(), np.abs(tsw[:, j] + v[:, 1 + j]).max())
        for j in range(2)
    )
    out.append("// Upstream tswspectral_layout(None, graph, 2, random_state=42**2,")
    out.append("// tol=1e-8) output (eigsh path); matches t1_embed_eigh up to sign")
    out.append("// to %.3g." % err)
    out.append(carr("t1_tsw_upstream", tsw))

    # ---- test_ensure_fallback_to_random_on_spectral_failure fixture -------
    dim = 1000
    np.random.seed(777)  # documented bake seed for the unseeded upstream draw
    u = np.random.random((dim, dim // 10))
    out.append("")
    out.append("// test_ensure_fallback_to_random_on_spectral_failure: upstream's")
    out.append("// u = np.random.random((1000, 100)) is unseeded; the C++ test bakes")
    out.append("// np.random.seed(777) and regenerates u via the bit-exact")
    out.append("// NumpyRandomState(777).random_sample() stream (row-major). Spot")
    out.append("// checks for that replication:")
    out.append("static const int t2_dim = %d;" % dim)
    out.append("static const int t2_ucols = %d;" % (dim // 10))
    out.append(carr("t2_u_head", u.ravel()[:5]))
    out.append(carr("t2_u_tail", u.ravel()[-3:]))
    out.append("static const double t2_u_mean = %.17g;" % u.mean())

    out.append("")
    out.append("}  // namespace golden_tsw")
    print("\n".join(out))


if __name__ == "__main__":
    main()
