#!/usr/bin/env python3
"""Generate golden values for inverse_transform (tests/golden_inverse.hpp).

Runs the *actual* reference UMAP (reference/umap + reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1, seeded) plus scipy.spatial.Delaunay from
the reference environment (scipy 1.18.1, the exact qhull_r 8.0.2 sources
vendored in third_party/qhull_r).

Sections:
  dt1/dt2/dt3) Delaunay-only banks: float32-quantised point sets ->
      Delaunay(points, incremental=True, qhull_options="QJ") simplices /
      neighbors / equations (bitwise) / paraboloid scale+shift / find_simplex
      over mixed inside/outside queries. Barycentric `transform` values are
      NOT baked: they differ from OpenBLAS by ~1e-15 (documented deviation in
      delaunay.hpp); find_simplex outputs are the integer consumers.
  iv1) small dense euclidean model (60x4, n_components=2, init="random",
      explicit a/b, n_epochs=100): fit embedding (bit-exact anchor),
      find_simplex of the queries, COO head/tail/weights, init_transform
      output, final inverse_transform points.
  iv2) 80x3 model with default n_epochs (fit 500, inverse 100): fit
      embedding, find_simplex, final points.
  iv3) metric="manhattan" 50x5 model (n_epochs=90 -> inverse 30): fit
      embedding, find_simplex, final points (exercises the manhattan_grad
      inverse metric).

All models use the small-data branch + init="random" + explicit a/b, i.e. the
fully deterministic path the C++ port reproduces bit-exactly.

Usage:
    NUMBA_NUM_THREADS=1 "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python \
        scripts/gen_golden_inverse.py > tests/golden_inverse.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402
import scipy.spatial  # noqa: E402

import umap.umap_ as um  # noqa: E402

# ------------------------------------------------------------- capture patch
captured = []
_orig_inv = um.optimize_layout_inverse


def _capturing_inv(head_embedding, tail_embedding, head, tail, weight, sigmas,
                   rhos, n_epochs, n_vertices, epochs_per_sample, *args,
                   **kwargs):
    captured.append({
        "init": head_embedding.copy(),
        "head": head.copy(),
        "tail": tail.copy(),
        "weight": weight.copy(),
        "n_epochs": n_epochs,
    })
    return _orig_inv(head_embedding, tail_embedding, head, tail, weight,
                     sigmas, rhos, n_epochs, n_vertices, epochs_per_sample,
                     *args, **kwargs)


um.optimize_layout_inverse = _capturing_inv


# ------------------------------------------------------------------ emitters
def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_inverse.py -- do not edit.")
out.append("// Golden values computed with the reference UMAP + scipy 1.18.1")
out.append("// Delaunay in reference/umap (+ reference/pynndescent),")
out.append("// NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_inverse {")

# ------------------------------------------------------- Delaunay-only banks
rng = np.random.RandomState(1234)
for name, (n, d, scale) in {
    "dt1": (40, 2, 10.0),
    "dt2": (120, 2, 8.0),
    "dt3": (35, 3, 5.0),
}.items():
    pts = rng.uniform(-scale, scale, size=(n, d)).astype(np.float32).astype(
        np.float64)
    nq = 30
    q = np.vstack([
        rng.uniform(-scale, scale, size=(nq // 2, d)),
        pts[rng.randint(0, n, nq // 4)] * 0.97,
        rng.uniform(-2 * scale, 2 * scale, size=(nq - nq // 2 - nq // 4, d)),
    ]).astype(np.float32).astype(np.float64)
    tri = scipy.spatial.Delaunay(pts, incremental=True, qhull_options="QJ")
    fs = tri.find_simplex(q)
    out.append("// ---- %s: n=%d d=%d nsimplex=%d" % (name, n, d,
                                                      tri.nsimplex))
    out.append("static const int %s_n = %d;" % (name, n))
    out.append("static const int %s_d = %d;" % (name, d))
    out.append("static const int %s_nq = %d;" % (name, nq))
    out.append("static const int %s_nsimplex = %d;" % (name, tri.nsimplex))
    out.append(carr("%s_points" % name, pts, "double"))
    out.append(carr("%s_queries" % name, q, "double"))
    out.append(carr("%s_simplices" % name, tri.simplices, "std::int32_t"))
    out.append(carr("%s_neighbors" % name, tri.neighbors, "std::int32_t"))
    out.append(carr("%s_equations" % name, tri.equations, "double"))
    out.append("static const double %s_pscale = %.17g;" %
               (name, tri.paraboloid_scale))
    out.append("static const double %s_pshift = %.17g;" %
               (name, tri.paraboloid_shift))
    out.append(carr("%s_find_simplex" % name, fs, "std::int32_t"))
    out.append("")


# ------------------------------------------------------------ model emitters
def make_blobs(rng, n, dim, centers, std):
    pts = []
    per = n // len(centers)
    for ci, c in enumerate(centers):
        cnt = per if ci < len(centers) - 1 else n - per * (len(centers) - 1)
        pts.append(rng.randn(cnt, dim) * std + np.asarray(c))
    return np.vstack(pts).astype(np.float32)


ab_a, ab_b = um.find_ab_params(1.0, 0.1)
out.append("static const double ab_a = %.17g;" % ab_a)
out.append("static const double ab_b = %.17g;" % ab_b)
out.append("")


def emit_case(prefix, X, queries, model):
    cap_idx = len(captured)
    model.fit(X)
    emb = model.embedding_
    # find_simplex over the queries, replicated exactly as inverse_transform
    # sees them (float32 queries).
    deltri = scipy.spatial.Delaunay(emb, incremental=True, qhull_options="QJ")
    fs = deltri.find_simplex(queries)
    inv = model.inverse_transform(queries)
    cap = captured[cap_idx]
    out.append("// ---- %s: metric=%s n_epochs=%s" %
               (prefix, model.metric, model.n_epochs))
    out.append("static const int %s_n = %d;" % (prefix, X.shape[0]))
    out.append("static const int %s_dim = %d;" % (prefix, X.shape[1]))
    out.append("static const int %s_nq = %d;" % (prefix, queries.shape[0]))
    out.append(carr("%s_X" % prefix, X))
    out.append(carr("%s_queries" % prefix, queries))
    out.append(carr("%s_embedding" % prefix, emb))
    out.append(carr("%s_find_simplex" % prefix, fs, "std::int32_t"))
    out.append("static const int %s_inv_n_epochs = %d;" %
               (prefix, cap["n_epochs"]))
    out.append(carr("%s_inv" % prefix, inv))
    return cap


rng = np.random.RandomState(99)

# iv1: 60x4 euclidean, n_epochs=100.
X1 = make_blobs(rng, 60, 4, [[0, 0, 0, 0], [4, 4, 4, 4], [-4, 4, -4, 4]], 0.8)
m1 = um.UMAP(n_neighbors=10, min_dist=0.01, n_epochs=100, init="random",
             random_state=42, a=ab_a, b=ab_b)
m1.fit(X1)
emb1 = m1.embedding_
# queries: pair midpoints (inside-ish), one exact training embedding point,
# two far-outside points (find_simplex -> -1, wraps to the last simplex).
q1 = np.vstack([
    (emb1[3] + emb1[17]) / 2,
    (emb1[10] + emb1[40]) / 2,
    (emb1[25] + emb1[55]) / 2,
    emb1[7],
    emb1.mean(axis=0),
    emb1[12] * 0.9 + emb1[33] * 0.1,
    emb1.max(axis=0) * 3.0 + 10.0,
    emb1.min(axis=0) * 3.0 - 10.0,
]).astype(np.float32)
m1b = um.UMAP(n_neighbors=10, min_dist=0.01, n_epochs=100, init="random",
              random_state=42, a=ab_a, b=ab_b)
cap1 = emit_case("iv1", X1, q1, m1b)
out.append(carr("iv1_head", cap1["head"], "std::int32_t"))
out.append(carr("iv1_tail", cap1["tail"], "std::int32_t"))
out.append(carr("iv1_weight", cap1["weight"], "double"))
out.append(carr("iv1_init", cap1["init"]))
out.append("")

# iv2: 80x3 euclidean, default n_epochs.
X2 = make_blobs(rng, 80, 3, [[0, 0, 0], [5, 5, 5], [5, -5, 0], [-5, 0, 5]],
                1.0)
m2 = um.UMAP(n_neighbors=12, min_dist=0.05, init="random", random_state=17,
             a=ab_a, b=ab_b)
m2.fit(X2)
emb2 = m2.embedding_
q2 = np.vstack([
    (emb2[i] + emb2[j]) / 2
    for (i, j) in [(0, 40), (5, 60), (11, 22), (30, 70), (44, 45), (2, 79)]
] + [emb2.mean(axis=0), emb2.max(axis=0) * 2.5 + 5.0]).astype(np.float32)
m2b = um.UMAP(n_neighbors=12, min_dist=0.05, init="random", random_state=17,
              a=ab_a, b=ab_b)
emit_case("iv2", X2, q2, m2b)
out.append("")

# iv3: 50x5 manhattan, n_epochs=90 -> inverse 30 epochs.
X3 = make_blobs(rng, 50, 5, [[0] * 5, [6] * 5], 1.2)
m3 = um.UMAP(n_neighbors=8, metric="manhattan", n_epochs=90, init="random",
             random_state=7, a=ab_a, b=ab_b)
m3.fit(X3)
emb3 = m3.embedding_
q3 = np.vstack([
    (emb3[i] + emb3[j]) / 2 for (i, j) in [(1, 30), (9, 41), (20, 21)]
] + [emb3.mean(axis=0), emb3.min(axis=0) * 2.0 - 4.0]).astype(np.float32)
m3b = um.UMAP(n_neighbors=8, metric="manhattan", n_epochs=90, init="random",
              random_state=7, a=ab_a, b=ab_b)
emit_case("iv3", X3, q3, m3b)
out.append("")

out.append("}  // namespace golden_inverse")
print("\n".join(out))
print("// iv cases captured: %d" % len(captured), file=sys.stderr)
