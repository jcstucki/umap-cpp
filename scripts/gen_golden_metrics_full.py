rng = np.random.RandomState(1234)

# ------------------------------------------------------------- input vectors
a6 = rng.uniform(-2.0, 2.0, 6)
b6 = rng.uniform(-2.0, 2.0, 6)
p6 = rng.uniform(0.05, 1.5, 6)
q6 = rng.uniform(0.05, 1.5, 6)
s6 = rng.uniform(0.5, 2.0, 6)        # seuclidean sigma
w6 = rng.uniform(0.1, 2.0, 6)        # wminkowski weights
z6 = np.zeros(6)
A = rng.randn(6, 6)
V6 = A @ A.T + 6.0 * np.eye(6)
vinv6 = np.linalg.inv(V6)

bin1 = (rng.rand(10) > 0.5).astype(np.float64)
bin2 = (rng.rand(10) > 0.5).astype(np.float64)
bin_zero = np.zeros(10)
bin_ones = np.ones(10)

h1 = rng.uniform(-1.5, 1.5, 2)
h2 = rng.uniform(-1.5, 1.5, 2)

u3 = rng.randn(3) * 0.3
v3 = rng.randn(3) * 0.3

counts1 = np.array([2.0, 5.0, 0.0, 3.0, 1.0, 8.0])
counts2 = np.array([1.0, 4.0, 2.0, 0.0, 6.0, 2.0])

const6 = np.full(6, 2.5)

sg1 = np.array([0.5, -0.3, 0.8])
sg2 = np.array([-0.2, 0.9, -0.4])
dg1 = np.array([0.5, -0.3, 0.8, 0.6])
dg2 = np.array([-0.2, 0.9, -0.4, 0.3])
dg_zero1 = np.array([0.5, 0.2, 0.0, 0.3])
dg_zero2 = np.array([0.0, 0.0, 0.0, 0.1])
ge1 = np.array([0.5, -0.3, 0.8, 0.6, 0.7])
ge2 = np.array([-0.2, 0.9, -0.4, 0.3, -1.9])
hyp4a = rng.randn(4)
hyp4b = rng.randn(4)

for name, arr in [
    ("mf_a6", a6), ("mf_b6", b6), ("mf_p6", p6), ("mf_q6", q6),
    ("mf_s6", s6), ("mf_w6", w6), ("mf_vinv6", vinv6),
    ("mf_bin1", bin1), ("mf_bin2", bin2),
    ("mf_h1", h1), ("mf_h2", h2), ("mf_u3", u3), ("mf_v3", v3),
    ("mf_counts1", counts1), ("mf_counts2", counts2), ("mf_const6", const6),
    ("mf_sg1", sg1), ("mf_sg2", sg2), ("mf_dg1", dg1), ("mf_dg2", dg2),
    ("mf_dg_zero1", dg_zero1), ("mf_dg_zero2", dg_zero2),
    ("mf_ge1", ge1), ("mf_ge2", ge2), ("mf_hyp4a", hyp4a), ("mf_hyp4b", hyp4b),
]:
    out.append(carr(name, arr))

# ------------------------------------------------------------ plain distances
scalars = []


def dval(name, v):
    scalars.append("static const double %s = %.17g;" % (name, v))


dval("d_seuclidean_a6_b6", dist.standardised_euclidean(a6, b6, s6))
dval("d_seuclidean_p6_q6", dist.standardised_euclidean(p6, q6, s6))
dval("d_seuclidean_same", dist.standardised_euclidean(a6, a6.copy(), s6))
dval("d_wminkowski_p3_a6_b6", dist.weighted_minkowski(a6, b6, w6, 3.0))
dval("d_wminkowski_p25_a6_b6", dist.weighted_minkowski(a6, b6, w6, 2.5))
dval("d_mahalanobis_a6_b6", dist.mahalanobis(a6, b6, vinv6))
dval("d_mahalanobis_same", dist.mahalanobis(a6, a6.copy(), vinv6))
dval("d_matching_b1_b2", dist.matching(bin1, bin2))
dval("d_matching_same", dist.matching(bin1, bin1.copy()))
dval("d_matching_z_o", dist.matching(bin_zero, bin_ones))
dval("d_kulsinski_b1_b2", dist.kulsinski(bin1, bin2))
dval("d_kulsinski_same", dist.kulsinski(bin1, bin1.copy()))
dval("d_kulsinski_z_o", dist.kulsinski(bin_zero, bin_ones))
dval("d_rogerstanimoto_b1_b2", dist.rogers_tanimoto(bin1, bin2))
dval("d_rogerstanimoto_same", dist.rogers_tanimoto(bin1, bin1.copy()))
dval("d_rogerstanimoto_z_o", dist.rogers_tanimoto(bin_zero, bin_ones))
dval("d_russellrao_b1_b2", dist.russellrao(bin1, bin2))
dval("d_russellrao_same", dist.russellrao(bin1, bin1.copy()))
dval("d_russellrao_ones", dist.russellrao(bin_ones, bin_ones.copy()))
dval("d_russellrao_z_o", dist.russellrao(bin_zero, bin_ones))
dval("d_sokalmichener_b1_b2", dist.sokal_michener(bin1, bin2))
dval("d_sokalmichener_same", dist.sokal_michener(bin1, bin1.copy()))
