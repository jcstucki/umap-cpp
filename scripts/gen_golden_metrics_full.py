dval("d_sokalsneath_same", dist.sokal_sneath(bin1, bin1.copy()))
dval("d_sokalsneath_z_z", dist.sokal_sneath(bin_zero, bin_zero.copy()))
dval("d_yule_b1_b2", dist.yule(bin1, bin2))
dval("d_yule_same", dist.yule(bin1, bin1.copy()))
dval("d_yule_z_o", dist.yule(bin_zero, bin_ones))
dval("d_haversine_h1_h2", dist.haversine(h1, h2))
dval("d_haversine_same", dist.haversine(h1, h1.copy()))
dval("d_poincare_u3_v3", dist.poincare(u3, v3))
dval("d_ll_dirichlet_c1_c2", dist.ll_dirichlet(counts1, counts2))
dval("d_ll_dirichlet_c2_c1", dist.ll_dirichlet(counts2, counts1))
dval("d_symmetric_kl_p6_q6", dist.symmetric_kl(p6.copy(), q6.copy()))
dval("d_symmetric_kl_c1_c2", dist.symmetric_kl(counts1.copy(), counts2.copy()))
dval("d_symmetric_kl_z01_p6_q6",
     dist.symmetric_kl(p6.copy(), q6.copy(), 0.01))
dval("d_softmax_hellinger_a6_b6", dist.softmax_hellinger(a6, b6))
dval("d_softmax_hellinger_same", dist.softmax_hellinger(a6, a6.copy()))

# helpers
dval("d_approx_log_gamma_7_3", dist.approx_log_Gamma(7.3))
dval("d_log_beta_2_3", dist.log_beta(2.0, 3.0))
dval("d_log_beta_7_11", dist.log_beta(7.0, 11.0))
dval("d_log_single_beta_4_2", dist.log_single_beta(4.2))

# special discrete (py_func where numba can't take the argument types)
dval("d_categorical_eq", dist.categorical_distance(3.0, 3.0))
dval("d_categorical_ne", dist.categorical_distance(3.0, 5.0))
dval("d_ordinal_2_7", dist.ordinal_distance(2.0, 7.0, 4.5))
dval("d_count_3_9", dist.count_distance(3.0, 9.0, 2.5, 1.7))
dval("d_count_11_15", dist.count_distance(11.0, 15.0, 2.5, 1.7))
# (lo = 0 yields inf via log(0) upstream and here alike; use lo = 1.)
dval("d_count_1_4", dist.count_distance(1.0, 4.0, 1.0, 1.0))
hier = [{1.0: 0.0, 2.0: 0.0, 3.0: 1.0}, {1.0: 0.0, 2.0: 1.0, 3.0: 2.0}]
hier_fn = dist.hierarchical_categorical_distance.py_func
dval("d_hier_1_2", hier_fn(1.0, 2.0, hier))
dval("d_hier_1_3", hier_fn(1.0, 3.0, hier))
dval("d_hier_1_1", hier_fn(1.0, 1.0, hier))
lev = dist.levenshtein.py_func
myers = dist.levenshtein_myers_ascii.py_func
dval("d_lev_kitten", lev("kitten", "sitting", 1.0, 20))
dval("d_lev_same", lev("abc", "abc", 1.0, 20))
dval("d_lev_empty", lev("", "abc", 1.0, 20))
dval("d_lev_norm", lev("levenshtein", "meilenstein", 2.0, 20))
dval("d_lev_maxdist", lev("a" * 30, "abc", 1.5, 20))
dval("d_myers_kitten", myers("kitten", "sitting", 1.0, 20))
dval("d_myers_same", myers("abc", "abc", 1.0, 20))
dval("d_myers_norm", myers("levenshtein", "meilenstein", 2.0, 20))
dval("d_myers_long", myers("x" * 70, "x" * 60 + "abcdefghij", 1.0, 20))

out.extend(scalars)

# ---------------------------------------------------------------- gradients
grad_cases = []


