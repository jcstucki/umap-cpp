#!/usr/bin/env python3
"""Generate golden values for the supervised-fit tests (tests/golden_supervised.hpp).

Runs the *actual* reference UMAP (reference/umap + reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1, seeded random_state) with y targets,
capturing per case:
  - X, y and the model hyperparameters,
  - the intersected graph_ (canonical CSR) after the supervised block,
  - the initial embedding as passed to optimize_layout_euclidean,
  - the final embedding.

All cases use the small-data branch (n < 4096), init="random" and explicit
a/b, i.e. the fully deterministic path the C++ port reproduces bit-exactly.

Cases:
  s1) categorical y with -1 unknowns, target_weight=0.5 (defaults)
  s2) categorical, target_weight=0.8, no unknowns
  s3) categorical, target_weight=1.0 (far_dist=1e12; may disconnect vertices)
  s4) general target: target_metric="l2", continuous y, target_n_neighbors=8,
      target_weight=0.5 (pow on the left operand)
  s5) general target: target_metric="l2", target_weight=0.3 (pow on the right)
  s6) discrete target: target_metric="ordinal" (get_discrete_params
      support_size), integer y, target_weight=0.5

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python \
        scripts/gen_golden_supervised.py > tests/golden_supervised.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "reference", "pynndescent"))
sys.path.insert(0, os.path.join(REPO, "reference", "umap"))

import numpy as np  # noqa: E402

import umap.umap_ as um  # noqa: E402

# ------------------------------------------------------------- capture patch
captured = []
_orig_opt = um.optimize_layout_euclidean


def _capturing_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                   n_vertices, epochs_per_sample, a, b, rng_state, *args,
                   **kwargs):
    captured.append({"init": head_embedding.copy(), "n_epochs": n_epochs})
    return _orig_opt(head_embedding, tail_embedding, head, tail, n_epochs,
                     n_vertices, epochs_per_sample, a, b, rng_state, *args,
                     **kwargs)


um.optimize_layout_euclidean = _capturing_opt


# ------------------------------------------------------------------ emitters
def fmt_float(v):
    v = float(v)
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    elif ctype == "double":
        vals = ", ".join("%.17g" % float(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


out = []
out.append("// Auto-generated by scripts/gen_golden_supervised.py -- do not edit.")
out.append("// Golden values computed with the reference UMAP in reference/umap")
out.append("// (+ reference/pynndescent), NUMBA_NUM_THREADS=1.")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_supervised {")


def make_blobs(rng, n, dim, centers, std):
    pts, labels = [], []
    per = n // len(centers)
    for ci, c in enumerate(centers):
        cnt = per if ci < len(centers) - 1 else n - per * (len(centers) - 1)
        pts.append(rng.randn(cnt, dim) * std + np.asarray(c))
        labels.extend([ci] * cnt)
    return np.vstack(pts).astype(np.float32), np.asarray(labels, np.float64)


def emit_case(prefix, X, y, model):
    cap_idx = len(captured)
    emb = model.fit_transform(X, y)
    cap = captured[cap_idx]
    g = model.graph_.tocsr().copy()
    g.sort_indices()
    out.append("// ---- %s: target_metric=%s target_weight=%s "
               "target_n_neighbors=%s" % (prefix, model.target_metric,
                                          model.target_weight,
                                          model.target_n_neighbors))
    out.append(carr("%s_y" % prefix, y))
    out.append(carr("%s_graph_indptr" % prefix, g.indptr, "std::int32_t"))
    out.append(carr("%s_graph_indices" % prefix, g.indices, "std::int32_t"))
    out.append(carr("%s_graph_data" % prefix, g.data))
    out.append(carr("%s_fit_init" % prefix, cap["init"]))
    out.append("static const int %s_fit_n_epochs = %d;" % (prefix,
                                                           cap["n_epochs"]))
    out.append(carr("%s_embedding" % prefix, emb))
    out.append("")
    return emb


# Shared dataset: 150x6 blobs, 3 classes (labels follow the blobs).
centers6 = [[0.0] * 6,
            [2.0, 1.5, 0.0, -1.0, 0.5, 1.0],
            [-1.5, 2.0, 1.0, 0.5, -1.0, 0.0]]
X, labels = make_blobs(np.random.RandomState(1234), 150, 6, centers6, 0.8)
out.append("static const std::int64_t sn = %d;" % X.shape[0])
out.append("static const std::int64_t sdim = %d;" % X.shape[1])
out.append(carr("sX", X))

ab_a, ab_b = um.find_ab_params(1.0, 0.1)
out.append("static const double sup_a = %.17g;" % ab_a)
out.append("static const double sup_b = %.17g;" % ab_b)
out.append("")

# s1: categorical with -1 unknowns, default target_weight=0.5.
y1 = labels.copy()
y1[::7] = -1.0  # semi-supervised: every 7th label unknown
m1 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b)
emit_case("s1", X, y1, m1)

# s2: categorical, target_weight=0.8, fully labelled.
m2 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
             target_weight=0.8)
emit_case("s2", X, labels.copy(), m2)

# s3: categorical, target_weight=1.0 -> far_dist=1e12.
m3 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
             target_weight=1.0)
emit_case("s3", X, labels.copy(), m3)

# s4/s5: general target branch, continuous y (noisy label value).
ycont = labels + 0.25 * np.random.RandomState(7).randn(len(labels))
ycont = ycont.astype(np.float32).astype(np.float64)  # f32-representable
m4 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
             target_metric="l2", target_n_neighbors=8)
emit_case("s4", X, ycont.copy(), m4)

m5 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
             target_metric="l2", target_weight=0.3)
emit_case("s5", X, ycont.copy(), m5)

# s6: discrete target branch, target_metric="ordinal".
yord = np.floor(labels * 2 + np.random.RandomState(11).randint(0, 2,
                                                               len(labels)))
yord = yord.astype(np.float64)
m6 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b,
             target_metric="ordinal")
emit_case("s6", X, yord, m6)

# Unsupervised baseline embedding for the label-separation behavioral test.
m0 = um.UMAP(init="random", random_state=42, a=ab_a, b=ab_b)
emb0 = m0.fit_transform(X)
out.append("// Unsupervised baseline for the label-separation test.")
out.append(carr("s0_embedding", emb0))
out.append(carr("s_labels", labels, "std::int32_t"))
out.append("")

out.append("}  // namespace golden_supervised")
print("\n".join(out))
