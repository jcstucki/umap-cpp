# --------------------------------------------- end-to-end sparse NN-descent
def nnd_golden(tag, X, k, metric):
    n = X.shape[0]
    n_trees = min(64, 5 + int(round(n ** 0.5 / 20.0)))
    n_iters = max(5, int(round(np.log2(n))))
    index = NNDescent(
        X,
        n_neighbors=k,
        metric=metric,
        random_state=42,
        n_trees=n_trees,
        n_iters=n_iters,
        max_candidates=60,
        low_memory=True,
        compressed=False,
        verbose=False,
    )
    ind, dist = index.neighbor_graph
    lines = csr_arrays(tag, X)
    lines.append("static const std::int64_t %s_k = %d;" % (tag, k))
    lines.append(carr("%s_knn_ind" % tag, ind, "std::int32_t"))
    lines.append(carr("%s_knn_dist" % tag, dist.astype(np.float32), "float"))
    return lines

# hellinger: nonnegative values (scipy.sparse.random draws in [0, 1)).
