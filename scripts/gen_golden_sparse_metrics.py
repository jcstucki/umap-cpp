def fmt_float(v):
    v = float(v)
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    if np.isnan(v):
        return "std::numeric_limits<float>::quiet_NaN()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s and "inf" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


def csr_arrays(name, X):
    assert X.has_sorted_indices
    return [
        "static const std::int64_t %s_n = %d;" % (name, X.shape[0]),
        "static const std::int64_t %s_dim = %d;" % (name, X.shape[1]),
        carr("%s_indptr" % name, X.indptr, "std::int32_t"),
        carr("%s_indices" % name, X.indices, "std::int32_t"),
        carr("%s_data" % name, X.data, "float"),
    ]


def emit_pair_bank(out, tag, pairs):
    offsets = [0]
    p_ind, p_dat = [], []
    for i1, d1, i2, d2 in pairs:
        p_ind.append(i1)
        p_dat.append(d1)
        offsets.append(offsets[-1] + len(i1))
        p_ind.append(i2)
        p_dat.append(d2)
        offsets.append(offsets[-1] + len(i2))
    out.append("static const std::int64_t %s_n_pairs = %d;" % (tag, len(pairs)))
    out.append(carr("%s_vec_offsets" % tag, offsets, "std::int32_t"))
    out.append(carr("%s_vec_ind" % tag,
                    np.concatenate(p_ind) if p_ind else np.array([], np.int32),
                    "std::int32_t"))
    out.append(carr("%s_vec_data" % tag,
                    np.concatenate(p_dat) if p_dat else np.array([], np.float32),
                    "float"))


