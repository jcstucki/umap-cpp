"""Generate golden values for the full sparse metric registry
(tests/golden_sparse_metrics.hpp).

Runs the *actual* reference implementations (numba-jitted) checked out under
reference/: pynndescent's sparse.py kernels (what NN-descent calls) for every
sparse_named_distances metric + the fast alternatives/corrections, and
umap/sparse.py's sparse_ll_dirichlet (umap-only). Also emits end-to-end
NNDescent kNN goldens for the newly enabled angular metrics (hellinger,
jaccard) and a brute-force hellinger kNN golden.

As a sanity check, metrics present in BOTH registries are cross-checked
(pynndescent vs umap copies) and the max relative difference is reported on
stderr (the implementations are identical up to numba typing details;
goldens are the pynndescent values, which the NN-descent path consumes).

Usage:
    NUMBA_NUM_THREADS=1 "${UMAPREF_VENV:-$HOME/.venvs/umapref-venv}"/bin/python \
        scripts/gen_golden_sparse_metrics.py > tests/golden_sparse_metrics.hpp
"""
