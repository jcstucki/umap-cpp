    (np.array([1, 5, 9], np.int32), np.array([0.5, -1.5, 2.0], np.float32),
     np.array([0, 4, 12], np.int32), np.array([1.0, 3.0, -0.25], np.float32)),
    (v1_i, v1_d, v1_i, v1_d.copy()),
    # equal values on all shared columns (diff cancels there)
