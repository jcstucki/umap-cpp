# ------------------------------------- brute-force hellinger kNN golden
# The C++ small-data path scans the *true* sparse metric (documented
# deviation from sklearn/pairwise_special_metric); golden = the same
# pynndescent kernel + stable argsort, so indices AND f4 dists must match
# bit-exactly.
rsb = np.random.RandomState(777)
bfh_X = scipy.sparse.random(
    60, 25, density=0.25, format="csr", random_state=rsb, dtype=np.float32
)
bfh_X.sort_indices()
out.extend(csr_arrays("bfh", bfh_X))
n = bfh_X.shape[0]
dmat = np.zeros((n, n), dtype=np.float32)
for i in range(n):
    si, ei = bfh_X.indptr[i], bfh_X.indptr[i + 1]
    for j in range(n):
        sj, ej = bfh_X.indptr[j], bfh_X.indptr[j + 1]
        dmat[i, j] = np.float32(pysparse.sparse_hellinger(
            bfh_X.indices[si:ei], bfh_X.data[si:ei],
            bfh_X.indices[sj:ej], bfh_X.data[sj:ej]))
knn_ind = np.argsort(dmat, kind="stable")[:, :8].astype(np.int32)
knn_dist = dmat[np.arange(n)[:, None], knn_ind]
out.append("static const std::int64_t bfh_k = 8;")
out.append(carr("bfh_knn_ind", knn_ind, "std::int32_t"))
out.append(carr("bfh_knn_dist", knn_dist, "float"))

out.append("}  // namespace golden_sparse_metrics")
print("\n".join(out))
