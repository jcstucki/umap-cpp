#!/usr/bin/env python3
"""Generate golden values for the sparse query-path port
(tests/golden_sparse_query.hpp).

Fits the *actual* reference pynndescent NNDescent (reference/pynndescent,
numba-jitted, NUMBA_NUM_THREADS=1) on sparse CSR data with the exact
parameters UMAP's nearest_neighbors uses, calls prepare(), and queries
held-out sparse points -- goldening both the prepared artifacts
(_vertex_order, _search_graph, the sparse _search_forest[0] tree with its
hyperplanes trimmed to their true lengths, _min_distance, warmed
search_rng_state) and the query results at epsilon=0.1 plus UMAP's
transform() epsilon (0.12 euclidean / 0.24 angular), so the C++
SparsePreparedIndex can be validated stage by stage.

Query rows are guaranteed non-empty: the reference's sparse_select_side /
sparse_dot_product reads index 0 of the query slice before checking sizes,
so an empty query row is undefined behaviour upstream (the C++ port guards
it, but goldens must stay in defined territory).

Usage:
    NUMBA_NUM_THREADS=1 /tmp/umapref-venv/bin/python \
        scripts/gen_golden_sparse_query.py > tests/golden_sparse_query.hpp
"""
import os
import sys

os.environ.setdefault("NUMBA_NUM_THREADS", "1")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_CANDIDATE_REFS = [
    os.path.join(REPO, "reference"),
    "/Users/jake/Desktop/Code Projects/git repos/UMAP-C++/reference",
]
for _ref in _CANDIDATE_REFS:
    if os.path.isdir(os.path.join(_ref, "pynndescent")):
        sys.path.insert(0, os.path.join(_ref, "pynndescent"))
        break
else:
    raise SystemExit("reference/pynndescent not found")

import numpy as np  # noqa: E402
import scipy.sparse  # noqa: E402

from pynndescent import NNDescent  # noqa: E402


def fmt_float(v):
    v = float(v)
    if np.isinf(v):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    s = "%.9g" % v
    if "." not in s and "e" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def carr(name, values, ctype="float"):
    flat = np.asarray(values).ravel()
    if ctype == "float":
        vals = ", ".join(fmt_float(v) for v in flat)
    elif ctype in ("std::int32_t", "std::int8_t", "std::uint8_t", "int"):
        vals = ", ".join(str(int(v)) for v in flat)
    elif ctype == "std::int64_t":
        vals = ", ".join("%dLL" % int(v) for v in flat)
    else:
        raise ValueError(ctype)
    return "static const %s %s[] = {%s};" % (ctype, name, vals)


def csr_arrays(name, X):
    assert X.has_sorted_indices
    return [
        "static const std::int64_t %s_n = %d;" % (name, X.shape[0]),
        "static const std::int64_t %s_dim = %d;" % (name, X.shape[1]),
        carr("%s_indptr" % name, X.indptr, "std::int32_t"),
        carr("%s_indices" % name, X.indices, "std::int32_t"),
        carr("%s_data" % name, X.data, "float"),
    ]


def fill_nonempty(X):
    """Guarantee no all-zero rows (adds 0.5 at column i % dim)."""
    n, d = X.shape
    fill = scipy.sparse.csr_matrix(
        (np.full(n, 0.5, dtype=np.float32),
         (np.arange(n), np.arange(n) % d)),
        shape=(n, d),
    )
    X = (X + fill).tocsr().astype(np.float32)
    X.sort_indices()
    assert np.diff(X.indptr).min() > 0
    return X


out = []
out.append("// Auto-generated by scripts/gen_golden_sparse_query.py -- do not"
           " edit by hand.")
out.append("// Golden values computed with the reference pynndescent in"
           " reference/pynndescent")
out.append("// (NUMBA_NUM_THREADS=1).")
out.append("#pragma once")
out.append("#include <cstdint>")
out.append("#include <limits>")
out.append("")
out.append("namespace golden_sparse_query {")


def trimmed_hyperplanes(tree):
    """Per-node sparse hyperplanes trimmed exactly like sparse_select_side:
    scan the padded float32 row 0 from the end while < 0."""
    n_nodes = tree.children.shape[0]
    hp_indptr = [0]
    hp_inds = []
    hp_data = []
    for i in range(n_nodes):
        row0 = tree.hyperplanes[i, 0, :]
        size = row0.shape[0]
        while size > 0 and row0[size - 1] < 0.0:
            size -= 1
        hp_inds.extend(row0[:size].astype(np.int32).tolist())
        hp_data.extend(tree.hyperplanes[i, 1, :size].tolist())
        hp_indptr.append(len(hp_inds))
    return (np.asarray(hp_indptr, dtype=np.int32),
            np.asarray(hp_inds, dtype=np.int32),
            np.asarray(hp_data, dtype=np.float32))


def run_case(tag, train, queries, metric, k=10, seed=42, n_neighbors=10,
             umap_epsilon=0.12):
    n = train.shape[0]
    # umap_.py::nearest_neighbors "hacked values" + fixed max_candidates
    n_trees = min(64, 5 + int(round(n ** 0.5 / 20.0)))
    n_iters = max(5, int(round(np.log2(n))))
    index = NNDescent(
        train,
        n_neighbors=n_neighbors,
        metric=metric,
        random_state=seed,
        n_trees=n_trees,
        n_iters=n_iters,
        max_candidates=60,
        low_memory=True,
        n_jobs=None,
        verbose=False,
        compressed=False,
    )
    index.prepare()
    assert index._is_sparse
    ind, dist = index.query(queries, k=k, epsilon=0.1)
    ind_u, dist_u = index.query(queries, k=k, epsilon=umap_epsilon)

    knn_ind, knn_dist = index.neighbor_graph

    tree = index._search_forest[0]
    hp_indptr, hp_inds, hp_data = trimmed_hyperplanes(tree)

    out.append("// ---- %s: %dx%d train (nnz %d), %d queries, metric=%s, k=%d,"
               " seed=%d"
               % (tag, n, train.shape[1], train.nnz, queries.shape[0], metric,
                  k, seed))
    out.extend(csr_arrays(tag, train))
    out.append("static const std::int64_t %s_nq = %d;" % (tag, queries.shape[0]))
    out.append(carr("%s_q_indptr" % tag, queries.indptr, "std::int32_t"))
    out.append(carr("%s_q_indices" % tag, queries.indices, "std::int32_t"))
    out.append(carr("%s_q_data" % tag, queries.data, "float"))
    out.append(carr("%s_search_rng_state" % tag, index.search_rng_state,
                    "std::int64_t"))
    out.append(carr("%s_knn_ind" % tag, knn_ind, "std::int32_t"))
    out.append(carr("%s_knn_dist" % tag, knn_dist.astype(np.float32), "float"))
    out.append(carr("%s_vertex_order" % tag, index._vertex_order,
                    "std::int32_t"))
    out.append(carr("%s_graph_indptr" % tag, index._search_graph.indptr,
                    "std::int32_t"))
    out.append(carr("%s_graph_indices" % tag, index._search_graph.indices,
                    "std::int32_t"))
    out.append("static const float %s_min_distance = %s;"
               % (tag, fmt_float(index._min_distance)))
    out.append("static const std::int64_t %s_tree_n_nodes = %d;"
               % (tag, tree.children.shape[0]))
    out.append(carr("%s_tree_children" % tag, tree.children, "std::int32_t"))
    out.append(carr("%s_tree_offsets" % tag, tree.offsets, "float"))
    out.append(carr("%s_tree_hp_indptr" % tag, hp_indptr, "std::int32_t"))
    out.append(carr("%s_tree_hp_inds" % tag, hp_inds, "std::int32_t"))
    out.append(carr("%s_tree_hp_data" % tag, hp_data, "float"))
    out.append(carr("%s_query_ind" % tag, ind, "std::int32_t"))
    out.append(carr("%s_query_dist" % tag, dist, "float"))
    out.append("static const float %s_umap_epsilon = %s;"
               % (tag, fmt_float(umap_epsilon)))
    out.append(carr("%s_query_ind_umap_eps" % tag, ind_u, "std::int32_t"))
    out.append(carr("%s_query_dist_umap_eps" % tag, dist_u, "float"))
    out.append("")


# Euclidean: raw scipy.sparse.random training data (empty train rows are
# legal and exercised); queries get the non-empty guarantee.
rs = np.random.RandomState(1234)
train_e = scipy.sparse.random(300, 50, density=0.1, format="csr",
                              random_state=rs, dtype=np.float32)
train_e.sort_indices()
query_e = scipy.sparse.random(20, 50, density=0.1, format="csr",
                              random_state=rs, dtype=np.float32)
query_e = fill_nonempty(query_e)
run_case("spe", train_e, query_e, "euclidean", umap_epsilon=0.12)

# Cosine (angular trees): non-empty rows everywhere so norms are non-zero.
rs = np.random.RandomState(5678)
train_c = scipy.sparse.random(300, 50, density=0.1, format="csr",
                              random_state=rs, dtype=np.float32)
train_c = fill_nonempty(train_c)
query_c = scipy.sparse.random(20, 50, density=0.1, format="csr",
                              random_state=rs, dtype=np.float32)
query_c = fill_nonempty(query_c)
run_case("spc", train_c, query_c, "cosine", umap_epsilon=0.24)

out.append("}  // namespace golden_sparse_query")
print("\n".join(out))
